/*
  Completa metadatos candidatos de entidades fiscales 2 y 3 en IOEDESARROLLO.
  ID 2: identidad desde FACT_CSD; conserva domicilio vacío por dos direcciones
  distintas en sucursales. ID 3: usa única dirección vinculada como candidata.
  Nunca cambia estado PENDIENTE, relaciones, tablas operativas o financieras.
  No consulta contenido CER/LLAVE ni credenciales PAC. Sin GO.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;

DECLARE @Aplicar bit=0,
        @ServidorEsperado nvarchar(128)=N'dd7842d7ba7e',
        @BaseEsperada sysname=N'IOEDESARROLLO';

IF LOWER(CONVERT(nvarchar(128),SERVERPROPERTY('ServerName')))<>LOWER(@ServidorEsperado)
  THROW 51031,'Servidor distinto del autorizado para este cambio.',1;
IF DB_NAME()<>@BaseEsperada
  THROW 51032,'Base distinta de IOEDESARROLLO.',1;
IF CONVERT(nvarchar(20),DATABASEPROPERTYEX(DB_NAME(),'Updateability'))<>N'READ_WRITE'
  THROW 51033,'IOEDESARROLLO no está en modo READ_WRITE.',1;
IF NOT EXISTS(SELECT 1 FROM sys.databases WHERE name=DB_NAME() AND state_desc='ONLINE')
  THROW 51034,'Base no está ONLINE.',1;

DECLARE @Targets TABLE(
  ID_ENTIDAD_FISCAL int PRIMARY KEY,
  EXPECTED_BRANCHES int NOT NULL,
  EXPECTED_ADDRESS_VARIANTS int NOT NULL,
  COPY_ADDRESS bit NOT NULL
);
INSERT @Targets VALUES(2,7,2,0),(3,1,1,1);

DECLARE @ExpectedBranches TABLE(
  ID_ENTIDAD_FISCAL int NOT NULL,
  SUC nvarchar(10) NOT NULL,
  PRIMARY KEY(ID_ENTIDAD_FISCAL,SUC)
);
INSERT @ExpectedBranches VALUES
  (2,N'DF02'),(2,N'DF03'),(2,N'DF05'),(2,N'DF06'),(2,N'DF10'),(2,N'DF14'),(2,N'OM01'),
  (3,N'DF04');
DECLARE @ExpectedAddressBranches TABLE(
  ID_ENTIDAD_FISCAL int NOT NULL,
  SUC nvarchar(10) NOT NULL,
  PRIMARY KEY(ID_ENTIDAD_FISCAL,SUC)
);
INSERT @ExpectedAddressBranches VALUES(2,N'DF05'),(2,N'DF14'),(3,N'DF04');

DECLARE @SucursalBefore bigint,
        @EmpresaBefore bigint,
        @CsdBefore bigint,
        @MovimientosBefore bigint,
        @AuditoriaBefore bigint;

BEGIN TRY
  BEGIN TRANSACTION;

  SELECT @SucursalBefore=COUNT_BIG(*) FROM dbo.DAT_SUC;
  SELECT @EmpresaBefore=COUNT_BIG(*) FROM dbo.EMPRESA;
  SELECT @CsdBefore=COUNT_BIG(*) FROM dbo.FACT_CSD;
  SELECT @MovimientosBefore=COUNT_BIG(*) FROM dbo.DAT_CTRL_CTAS;
  SELECT @AuditoriaBefore=COUNT_BIG(*) FROM dbo.ENTIDAD_FISCAL_AUDIT;

  CREATE TABLE #Work(
    ID_ENTIDAD_FISCAL int NOT NULL PRIMARY KEY,
    VERSION_ANTES binary(8) NOT NULL,
    RFC nvarchar(20) NOT NULL,
    ESTADO varchar(12) NOT NULL,
    NOMBRE_ACTUAL nvarchar(300) NULL,
    REGIMEN_ACTUAL varchar(3) NULL,
    CP_ACTUAL char(5) NULL,
    DOMICILIO_ACTUAL nvarchar(500) NULL,
    REFERENCIA_ACTUAL nvarchar(250) NULL,
    VALIDADO_POR_ACTUAL nvarchar(255) NULL,
    FCN_VALIDACION_ACTUAL datetime2(7) NULL,
    CSD_COUNT int NOT NULL,
    CSD_ID int NULL,
    NOMBRE_FUENTE nvarchar(300) NULL,
    REGIMEN_FUENTE varchar(3) NULL,
    CP_FUENTE char(5) NULL,
    SOURCE_BRANCH_COUNT int NOT NULL,
    LINK_COUNT int NOT NULL,
    PENDING_LINK_COUNT int NOT NULL,
    ADDRESS_VARIANTS int NOT NULL,
    ADDRESS_SOURCE nvarchar(500) NULL,
    OP_COMPANY_COUNT int NOT NULL,
    OP_COMPANY_ID int NULL,
    OP_COMPANY_BAD_COUNT int NOT NULL,
    COPY_ADDRESS bit NOT NULL,
    EXPECTED_BRANCHES int NOT NULL,
    EXPECTED_ADDRESS_VARIANTS int NOT NULL
  );

  INSERT #Work(
    ID_ENTIDAD_FISCAL,VERSION_ANTES,RFC,ESTADO,NOMBRE_ACTUAL,REGIMEN_ACTUAL,CP_ACTUAL,DOMICILIO_ACTUAL,
    REFERENCIA_ACTUAL,VALIDADO_POR_ACTUAL,FCN_VALIDACION_ACTUAL,CSD_COUNT,CSD_ID,NOMBRE_FUENTE,REGIMEN_FUENTE,CP_FUENTE,
    SOURCE_BRANCH_COUNT,LINK_COUNT,PENDING_LINK_COUNT,ADDRESS_VARIANTS,ADDRESS_SOURCE,OP_COMPANY_COUNT,OP_COMPANY_ID,OP_COMPANY_BAD_COUNT,
    COPY_ADDRESS,EXPECTED_BRANCHES,EXPECTED_ADDRESS_VARIANTS
  )
  SELECT e.ID_ENTIDAD_FISCAL,e.VERSION,e.RFC,e.ESTADO_VALIDACION,e.NOMBRE_LEGAL,e.REGIMEN_FISCAL,e.CP_FISCAL,e.DOMICILIO_FISCAL,
         e.REFERENCIA_VALIDACION,e.VALIDADO_POR,e.FCN_VALIDACION_UTC,
         cs.CSD_COUNT,cs.CSD_ID,cs.NOMBRE_FUENTE,cs.REGIMEN_FUENTE,cs.CP_FUENTE,
         bs.SOURCE_BRANCH_COUNT,ls.LINK_COUNT,ls.PENDING_LINK_COUNT,bs.ADDRESS_VARIANTS,bs.ADDRESS_SOURCE,bs.OP_COMPANY_COUNT,bs.OP_COMPANY_ID,bs.OP_COMPANY_BAD_COUNT,
         t.COPY_ADDRESS,t.EXPECTED_BRANCHES,t.EXPECTED_ADDRESS_VARIANTS
  FROM @Targets t
  JOIN dbo.ENTIDAD_FISCAL e WITH(UPDLOCK,HOLDLOCK) ON e.ID_ENTIDAD_FISCAL=t.ID_ENTIDAD_FISCAL
  OUTER APPLY(
    SELECT COUNT(*) CSD_COUNT,MAX(c.ID) CSD_ID,
           MAX(NULLIF(LTRIM(RTRIM(c.NOMBRE)),N'')) NOMBRE_FUENTE,
           MAX(NULLIF(LTRIM(RTRIM(c.REGIMEN_FISCAL)),'')) REGIMEN_FUENTE,
           MAX(NULLIF(LTRIM(RTRIM(c.CODIGO_POSTAL)),'')) CP_FUENTE
    FROM dbo.FACT_CSD c WITH(HOLDLOCK)
    WHERE UPPER(LTRIM(RTRIM(c.RFC)))=UPPER(LTRIM(RTRIM(e.RFC)))
      AND c.ACTIVO=1
      AND c.VIGENCIA_DESDE<=SYSUTCDATETIME()
      AND c.VIGENCIA_HASTA>=SYSUTCDATETIME()
  ) cs
  OUTER APPLY(
    SELECT COUNT(DISTINCT s.SUC) SOURCE_BRANCH_COUNT,
           COUNT(DISTINCT NULLIF(LTRIM(RTRIM(s.DIRECCION)),N'')) ADDRESS_VARIANTS,
           MAX(NULLIF(LTRIM(RTRIM(s.DIRECCION)),N'')) ADDRESS_SOURCE,
           COUNT(DISTINCT s.IDEMPRESA) OP_COMPANY_COUNT,
           MIN(s.IDEMPRESA) OP_COMPANY_ID,
           SUM(CASE WHEN s.IDEMPRESA IS NULL OR s.IDEMPRESA<>1 THEN 1 ELSE 0 END) OP_COMPANY_BAD_COUNT
    FROM dbo.DAT_SUC s WITH(HOLDLOCK)
    WHERE UPPER(LTRIM(RTRIM(s.RFC)))=UPPER(LTRIM(RTRIM(e.RFC)))
  ) bs
  OUTER APPLY(
    SELECT COUNT(*) LINK_COUNT,
           SUM(CASE WHEN r.ESTADO_VALIDACION='PENDIENTE' THEN 1 ELSE 0 END) PENDING_LINK_COUNT
    FROM dbo.ENTIDAD_FISCAL_SUCURSAL r WITH(HOLDLOCK)
    WHERE r.ID_ENTIDAD_FISCAL=e.ID_ENTIDAD_FISCAL
  ) ls;

  IF (SELECT COUNT(*) FROM #Work)<>2
    THROW 51035,'No se encontraron exactamente entidades candidatas 2 y 3.',1;
  IF EXISTS(SELECT 1 FROM #Work WHERE ESTADO<>'PENDIENTE' OR REFERENCIA_ACTUAL IS NOT NULL OR VALIDADO_POR_ACTUAL IS NOT NULL OR FCN_VALIDACION_ACTUAL IS NOT NULL)
    THROW 51036,'Una entidad dejó de estar pendiente o recibió datos de validación.',1;
  IF EXISTS(SELECT 1 FROM #Work WHERE NOMBRE_ACTUAL IS NOT NULL OR REGIMEN_ACTUAL IS NOT NULL OR CP_ACTUAL IS NOT NULL OR DOMICILIO_ACTUAL IS NOT NULL)
    THROW 51037,'La ficha ya tiene valores; no sobrescribir sin revisión.',1;
  IF EXISTS(SELECT 1 FROM #Work WHERE CSD_COUNT<>1 OR NOMBRE_FUENTE IS NULL OR REGIMEN_FUENTE IS NULL OR CP_FUENTE IS NULL OR LEN(REGIMEN_FUENTE)<>3 OR CP_FUENTE NOT LIKE '[0-9][0-9][0-9][0-9][0-9]')
    THROW 51038,'Debe existir un único CSD vigente con nombre, régimen y CP válidos.',1;
  IF EXISTS(SELECT 1 FROM #Work WHERE SOURCE_BRANCH_COUNT<>EXPECTED_BRANCHES OR LINK_COUNT<>EXPECTED_BRANCHES OR PENDING_LINK_COUNT<>EXPECTED_BRANCHES OR ADDRESS_VARIANTS<>EXPECTED_ADDRESS_VARIANTS OR OP_COMPANY_COUNT<>1 OR OP_COMPANY_ID<>1 OR OP_COMPANY_BAD_COUNT<>0)
    THROW 51039,'Conteos de sucursales, direcciones o empresa operativa cambiaron.',1;
  IF (SELECT COUNT(*) FROM dbo.EMPRESA WITH(HOLDLOCK) WHERE idempresa=1)<>1
    THROW 51040,'La empresa operativa ID 1 ya no existe de forma única.',1;
  IF EXISTS(
      SELECT ID_ENTIDAD_FISCAL,SUC FROM @ExpectedBranches
      EXCEPT
      SELECT w.ID_ENTIDAD_FISCAL,s.SUC FROM #Work w JOIN dbo.DAT_SUC s WITH(HOLDLOCK)
        ON UPPER(LTRIM(RTRIM(s.RFC)))=UPPER(LTRIM(RTRIM(w.RFC)))
  ) OR EXISTS(
      SELECT w.ID_ENTIDAD_FISCAL,s.SUC FROM #Work w JOIN dbo.DAT_SUC s WITH(HOLDLOCK)
        ON UPPER(LTRIM(RTRIM(s.RFC)))=UPPER(LTRIM(RTRIM(w.RFC)))
      EXCEPT SELECT ID_ENTIDAD_FISCAL,SUC FROM @ExpectedBranches
  ) THROW 51041,'Las sucursales con el RFC candidato cambiaron.',1;
  IF EXISTS(
      SELECT ID_ENTIDAD_FISCAL,SUC FROM @ExpectedAddressBranches
      EXCEPT SELECT w.ID_ENTIDAD_FISCAL,s.SUC FROM #Work w JOIN dbo.DAT_SUC s WITH(HOLDLOCK)
        ON UPPER(LTRIM(RTRIM(s.RFC)))=UPPER(LTRIM(RTRIM(w.RFC))) AND NULLIF(LTRIM(RTRIM(s.DIRECCION)),N'') IS NOT NULL
  ) OR EXISTS(
      SELECT w.ID_ENTIDAD_FISCAL,s.SUC FROM #Work w JOIN dbo.DAT_SUC s WITH(HOLDLOCK)
        ON UPPER(LTRIM(RTRIM(s.RFC)))=UPPER(LTRIM(RTRIM(w.RFC))) AND NULLIF(LTRIM(RTRIM(s.DIRECCION)),N'') IS NOT NULL
      EXCEPT SELECT ID_ENTIDAD_FISCAL,SUC FROM @ExpectedAddressBranches
  ) THROW 51050,'Las sucursales con domicilio candidato cambiaron.',1;
  IF EXISTS(
      SELECT ID_ENTIDAD_FISCAL,SUC FROM @ExpectedBranches
      EXCEPT SELECT ID_ENTIDAD_FISCAL,SUC FROM dbo.ENTIDAD_FISCAL_SUCURSAL WITH(HOLDLOCK)
  ) OR EXISTS(
      SELECT ID_ENTIDAD_FISCAL,SUC FROM dbo.ENTIDAD_FISCAL_SUCURSAL WITH(HOLDLOCK) WHERE ID_ENTIDAD_FISCAL IN(2,3)
      EXCEPT SELECT ID_ENTIDAD_FISCAL,SUC FROM @ExpectedBranches
  ) THROW 51042,'Los vínculos fiscales de sucursal cambiaron.',1;
  IF EXISTS(SELECT 1 FROM #Work WHERE COPY_ADDRESS=1 AND (ADDRESS_VARIANTS<>1 OR ADDRESS_SOURCE IS NULL))
    THROW 51043,'La dirección candidata seleccionada dejó de ser única.',1;

  IF @Aplicar=0
  BEGIN
    SELECT 'READY_TO_APPLY' resultado,ID_ENTIDAD_FISCAL idEntidadFiscal,
           CSD_COUNT csdActivoVigente,SOURCE_BRANCH_COUNT sucursalesFuente,LINK_COUNT vinculos,
           ADDRESS_VARIANTS direccionesDistintas,COPY_ADDRESS domicilioCandidatoIncluido,
           PENDING_LINK_COUNT vinculosPendientes,sys.fn_varbintohexstr(VERSION_ANTES) versionAntes,
           CAST(0 AS bit) escrituras
    FROM #Work ORDER BY ID_ENTIDAD_FISCAL;
    ROLLBACK TRANSACTION;
    RETURN;
  END;

  DECLARE @Aplicados TABLE(ID_ENTIDAD_FISCAL int PRIMARY KEY,ID_AUDIT bigint NULL,VERSION_DESPUES binary(8));
  DECLARE @Auditorias TABLE(ID_ENTIDAD_FISCAL int PRIMARY KEY,ID_AUDIT bigint NOT NULL);
  UPDATE e
     SET NOMBRE_LEGAL=w.NOMBRE_FUENTE,
         REGIMEN_FISCAL=w.REGIMEN_FUENTE,
         CP_FISCAL=w.CP_FUENTE,
         DOMICILIO_FISCAL=CASE WHEN w.COPY_ADDRESS=1 THEN w.ADDRESS_SOURCE ELSE NULL END,
         MODIFICADO_POR=N'Codex:solicitud titular',
         FCN_MODIFICACION_UTC=SYSUTCDATETIME()
  OUTPUT inserted.ID_ENTIDAD_FISCAL,CAST(NULL AS bigint),inserted.VERSION INTO @Aplicados(ID_ENTIDAD_FISCAL,ID_AUDIT,VERSION_DESPUES)
  FROM dbo.ENTIDAD_FISCAL e
  JOIN #Work w ON w.ID_ENTIDAD_FISCAL=e.ID_ENTIDAD_FISCAL
  WHERE e.VERSION=w.VERSION_ANTES AND e.ESTADO_VALIDACION='PENDIENTE';
  IF @@ROWCOUNT<>2 THROW 51044,'Conflicto concurrente al actualizar candidatas 2 y 3.',1;

  INSERT dbo.ENTIDAD_FISCAL_AUDIT(ID_ENTIDAD_FISCAL,ID_RELACION,ACCION,CAMPOS_JSON,ACTOR)
  OUTPUT inserted.ID_ENTIDAD_FISCAL,inserted.ID_AUDIT INTO @Auditorias(ID_ENTIDAD_FISCAL,ID_AUDIT)
  SELECT w.ID_ENTIDAD_FISCAL,NULL,'CAMBIO',
         CASE WHEN w.COPY_ADDRESS=1
           THEN N'{"fields":["NOMBRE_LEGAL","REGIMEN_FISCAL","CP_FISCAL","DOMICILIO_FISCAL"],"sources":{"identity":"dbo.FACT_CSD","address":"dbo.DAT_SUC"},"statusAfter":"PENDIENTE","officialValidation":false}'
           ELSE N'{"fields":["NOMBRE_LEGAL","REGIMEN_FISCAL","CP_FISCAL"],"sources":{"identity":"dbo.FACT_CSD"},"addressLeftEmptyDueToMultipleBranchAddresses":true,"statusAfter":"PENDIENTE","officialValidation":false}' END,
         N'Codex:solicitud titular'
  FROM #Work w;

  UPDATE a SET ID_AUDIT=x.ID_AUDIT
  FROM @Aplicados a JOIN @Auditorias x ON x.ID_ENTIDAD_FISCAL=a.ID_ENTIDAD_FISCAL;

  IF (SELECT COUNT(*) FROM @Aplicados WHERE ID_AUDIT IS NOT NULL)<>2
    THROW 51045,'No se pudo asociar auditoría a las dos actualizaciones.',1;
  IF EXISTS(
      SELECT 1 FROM #Work w
      WHERE NOT EXISTS(SELECT 1 FROM dbo.ENTIDAD_FISCAL e WITH(HOLDLOCK)
        WHERE e.ID_ENTIDAD_FISCAL=w.ID_ENTIDAD_FISCAL
          AND e.NOMBRE_LEGAL=w.NOMBRE_FUENTE
          AND e.REGIMEN_FISCAL=w.REGIMEN_FUENTE
          AND e.CP_FISCAL=w.CP_FUENTE
          AND ((w.COPY_ADDRESS=1 AND e.DOMICILIO_FISCAL=w.ADDRESS_SOURCE) OR (w.COPY_ADDRESS=0 AND e.DOMICILIO_FISCAL IS NULL))
          AND e.ESTADO_VALIDACION='PENDIENTE' AND e.REFERENCIA_VALIDACION IS NULL
          AND e.VALIDADO_POR IS NULL AND e.FCN_VALIDACION_UTC IS NULL)
  ) THROW 51046,'Postflight de campos candidatos falló.',1;
  IF (SELECT COUNT(*) FROM dbo.ENTIDAD_FISCAL_SUCURSAL WITH(HOLDLOCK) WHERE ID_ENTIDAD_FISCAL IN(2,3) AND ESTADO_VALIDACION='PENDIENTE')<>8
    THROW 51047,'Postflight de vínculos pendientes falló.',1;
  IF (SELECT COUNT_BIG(*) FROM dbo.DAT_SUC)<>@SucursalBefore
     OR (SELECT COUNT_BIG(*) FROM dbo.EMPRESA)<>@EmpresaBefore
     OR (SELECT COUNT_BIG(*) FROM dbo.FACT_CSD)<>@CsdBefore
     OR (SELECT COUNT_BIG(*) FROM dbo.DAT_CTRL_CTAS)<>@MovimientosBefore
    THROW 51048,'Postflight detectó cambio en tablas operativas o financieras.',1;
  IF (SELECT COUNT_BIG(*) FROM dbo.ENTIDAD_FISCAL_AUDIT WITH(HOLDLOCK))<>@AuditoriaBefore+2
    THROW 51049,'Postflight de auditoría falló.',1;

  UPDATE a
     SET VERSION_DESPUES=e.VERSION
  FROM @Aplicados a JOIN dbo.ENTIDAD_FISCAL e WITH(HOLDLOCK) ON e.ID_ENTIDAD_FISCAL=a.ID_ENTIDAD_FISCAL;

  COMMIT TRANSACTION;

  SELECT 'APLICADO_Y_VERIFICADO' resultado,a.ID_ENTIDAD_FISCAL idEntidadFiscal,
         w.CSD_COUNT csdActivoVigente,w.SOURCE_BRANCH_COUNT sucursalesFuente,w.LINK_COUNT vinculos,
         w.ADDRESS_VARIANTS direccionesDistintas,w.COPY_ADDRESS domicilioCandidatoIncluido,
         w.PENDING_LINK_COUNT vinculosPendientes,a.ID_AUDIT idAuditoria,
         sys.fn_varbintohexstr(w.VERSION_ANTES) versionAntes,
         sys.fn_varbintohexstr(a.VERSION_DESPUES) versionDespues,
         CAST(0 AS bit) escriturasOperativas,CAST(0 AS bit) escriturasFinancieras,
         CAST(0 AS bit) validacionOficial
  FROM @Aplicados a JOIN #Work w ON w.ID_ENTIDAD_FISCAL=a.ID_ENTIDAD_FISCAL
  ORDER BY a.ID_ENTIDAD_FISCAL;
END TRY
BEGIN CATCH
  IF XACT_STATE()<>0 ROLLBACK TRANSACTION;
  THROW;
END CATCH;
