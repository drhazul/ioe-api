/*
  Correccion aditiva de identidad fiscal y relacion con sucursales.
  Instalador exclusivo de IOEDESARROLLO; el ejecutor reemplaza @Aplicar y @ServidorEsperado
  solo despues de preflight exacto y backup verificado. Sin GO.
  Crea candidatos PENDIENTE desde RFC de DAT_SUC con forma de persona fisica; no valida
  identidad legal, no modifica DAT_SUC/EMPRESA/FACT_CSD ni crea asientos.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;

DECLARE @Aplicar bit=0,
        @ServidorEsperado nvarchar(128)=NULL,
        @BaseEsperada sysname=N'IOEDESARROLLO';

IF DB_NAME()<>@BaseEsperada THROW 53301,'Script exclusivo de IOEDESARROLLO.',1;
IF @@TRANCOUNT<>0 THROW 53302,'Ejecutar sin transaccion externa.',1;

SELECT @@SERVERNAME servidor, DB_NAME() base,
       CASE WHEN OBJECT_ID(N'dbo.ENTIDAD_FISCAL',N'U') IS NULL THEN 0 ELSE 1 END entidad_fiscal,
       CASE WHEN OBJECT_ID(N'dbo.ENTIDAD_FISCAL_SUCURSAL',N'U') IS NULL THEN 0 ELSE 1 END entidad_fiscal_sucursal,
       CASE WHEN OBJECT_ID(N'dbo.ENTIDAD_FISCAL_AUDIT',N'U') IS NULL THEN 0 ELSE 1 END entidad_fiscal_audit;

IF @Aplicar=0 RETURN;
IF @ServidorEsperado IS NULL OR @@SERVERNAME<>@ServidorEsperado OR DB_NAME()<>@BaseEsperada
  THROW 53303,'Destino exacto requerido.',1;
IF OBJECT_ID(N'dbo.EMPRESA',N'U') IS NULL OR OBJECT_ID(N'dbo.DAT_SUC',N'U') IS NULL
  THROW 53304,'Faltan tablas base EMPRESA o DAT_SUC.',1;

DECLARE @Existentes int=
  (CASE WHEN OBJECT_ID(N'dbo.ENTIDAD_FISCAL',N'U') IS NULL THEN 0 ELSE 1 END)+
  (CASE WHEN OBJECT_ID(N'dbo.ENTIDAD_FISCAL_SUCURSAL',N'U') IS NULL THEN 0 ELSE 1 END)+
  (CASE WHEN OBJECT_ID(N'dbo.ENTIDAD_FISCAL_AUDIT',N'U') IS NULL THEN 0 ELSE 1 END);
IF @Existentes NOT IN (0,3) THROW 53305,'Esquema parcial; inspeccionar y preparar delta revisado.',1;
IF @Existentes=3 AND (
  OBJECT_ID(N'dbo.UQ_ENTIDAD_FISCAL_RFC') IS NULL OR
  OBJECT_ID(N'dbo.FK_ENTIDAD_FISCAL_SUCURSAL_ENTIDAD') IS NULL OR
  OBJECT_ID(N'dbo.FK_ENTIDAD_FISCAL_SUCURSAL_SUC') IS NULL OR
  OBJECT_ID(N'dbo.FK_ENTIDAD_FISCAL_AUDIT_ENTIDAD') IS NULL OR
  OBJECT_ID(N'dbo.FK_ENTIDAD_FISCAL_AUDIT_REL') IS NULL OR
  NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.ENTIDAD_FISCAL_SUCURSAL') AND name=N'UX_ENTIDAD_FISCAL_SUC_PENDIENTE') OR
  NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.ENTIDAD_FISCAL_SUCURSAL') AND name=N'IX_ENTIDAD_FISCAL_SUCURSAL_SUC_VIGENCIA') OR
  NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.ENTIDAD_FISCAL_SUCURSAL') AND name=N'IX_ENTIDAD_FISCAL_SUCURSAL_ENTIDAD') OR
  NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.ENTIDAD_FISCAL_AUDIT') AND name=N'IX_ENTIDAD_FISCAL_AUDIT_ENTIDAD')
) THROW 53306,'Esquema existente no coincide con version; inspeccionar antes de continuar.',1;

BEGIN TRY
  BEGIN TRAN;

  IF @Existentes=0
  BEGIN
    CREATE TABLE dbo.ENTIDAD_FISCAL(
      ID_ENTIDAD_FISCAL int IDENTITY(1,1) NOT NULL CONSTRAINT PK_ENTIDAD_FISCAL PRIMARY KEY,
      RFC nvarchar(20) NOT NULL,
      TIPO_PERSONA varchar(8) NOT NULL,
      NOMBRE_LEGAL nvarchar(300) NULL,
      NOMBRE_COMERCIAL nvarchar(200) NULL,
      REGIMEN_FISCAL varchar(3) NULL,
      CP_FISCAL char(5) NULL,
      DOMICILIO_FISCAL nvarchar(500) NULL,
      ESTADO_VALIDACION varchar(12) NOT NULL CONSTRAINT DF_ENTIDAD_FISCAL_ESTADO DEFAULT('PENDIENTE'),
      REFERENCIA_VALIDACION nvarchar(250) NULL,
      ORIGEN_CANDIDATO varchar(40) NULL,
      VALIDADO_POR nvarchar(255) NULL,
      FCN_VALIDACION_UTC datetime2(7) NULL,
      CREADO_POR nvarchar(255) NOT NULL,
      FCN_CREACION_UTC datetime2(7) NOT NULL CONSTRAINT DF_ENTIDAD_FISCAL_CREACION DEFAULT(SYSUTCDATETIME()),
      MODIFICADO_POR nvarchar(255) NOT NULL,
      FCN_MODIFICACION_UTC datetime2(7) NOT NULL CONSTRAINT DF_ENTIDAD_FISCAL_MODIFICACION DEFAULT(SYSUTCDATETIME()),
      VERSION rowversion NOT NULL,
      CONSTRAINT UQ_ENTIDAD_FISCAL_RFC UNIQUE(RFC),
      CONSTRAINT CK_ENTIDAD_FISCAL_RFC CHECK(LEN(RFC) IN (12,13)),
      CONSTRAINT CK_ENTIDAD_FISCAL_TIPO CHECK(TIPO_PERSONA IN ('FISICA','MORAL')),
      CONSTRAINT CK_ENTIDAD_FISCAL_ESTADO CHECK(ESTADO_VALIDACION IN ('PENDIENTE','VALIDADA','INACTIVA')),
      CONSTRAINT CK_ENTIDAD_FISCAL_CP CHECK(CP_FISCAL IS NULL OR CP_FISCAL LIKE '[0-9][0-9][0-9][0-9][0-9]'),
      CONSTRAINT CK_ENTIDAD_FISCAL_VALIDADA CHECK(ESTADO_VALIDACION<>'VALIDADA' OR
        (NOMBRE_LEGAL IS NOT NULL AND REGIMEN_FISCAL IS NOT NULL AND CP_FISCAL IS NOT NULL AND REFERENCIA_VALIDACION IS NOT NULL))
    );

    CREATE TABLE dbo.ENTIDAD_FISCAL_SUCURSAL(
      ID_RELACION bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_ENTIDAD_FISCAL_SUCURSAL PRIMARY KEY,
      ID_ENTIDAD_FISCAL int NOT NULL,
      SUC nvarchar(10) NOT NULL,
      VIGENTE_DESDE date NULL,
      VIGENTE_HASTA date NULL,
      ESTADO_VALIDACION varchar(12) NOT NULL CONSTRAINT DF_ENTIDAD_FISCAL_SUCURSAL_ESTADO DEFAULT('PENDIENTE'),
      ORIGEN varchar(40) NOT NULL,
      REFERENCIA_VALIDACION nvarchar(250) NULL,
      CREADO_POR nvarchar(255) NOT NULL,
      FCN_CREACION_UTC datetime2(7) NOT NULL CONSTRAINT DF_ENTIDAD_FISCAL_SUCURSAL_CREACION DEFAULT(SYSUTCDATETIME()),
      MODIFICADO_POR nvarchar(255) NOT NULL,
      FCN_MODIFICACION_UTC datetime2(7) NOT NULL CONSTRAINT DF_ENTIDAD_FISCAL_SUCURSAL_MODIFICACION DEFAULT(SYSUTCDATETIME()),
      VERSION rowversion NOT NULL,
      CONSTRAINT FK_ENTIDAD_FISCAL_SUCURSAL_ENTIDAD FOREIGN KEY(ID_ENTIDAD_FISCAL) REFERENCES dbo.ENTIDAD_FISCAL(ID_ENTIDAD_FISCAL),
      CONSTRAINT FK_ENTIDAD_FISCAL_SUCURSAL_SUC FOREIGN KEY(SUC) REFERENCES dbo.DAT_SUC(SUC),
      CONSTRAINT CK_ENTIDAD_FISCAL_SUCURSAL_ESTADO CHECK(ESTADO_VALIDACION IN ('PENDIENTE','VALIDADA','INACTIVA')),
      CONSTRAINT CK_ENTIDAD_FISCAL_SUCURSAL_VIGENCIA CHECK(VIGENTE_DESDE IS NULL OR VIGENTE_HASTA IS NULL OR VIGENTE_HASTA>=VIGENTE_DESDE),
      CONSTRAINT CK_ENTIDAD_FISCAL_SUCURSAL_VALIDADA CHECK(ESTADO_VALIDACION<>'VALIDADA' OR (VIGENTE_DESDE IS NOT NULL AND REFERENCIA_VALIDACION IS NOT NULL))
    );

    CREATE TABLE dbo.ENTIDAD_FISCAL_AUDIT(
      ID_AUDIT bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_ENTIDAD_FISCAL_AUDIT PRIMARY KEY,
      ID_ENTIDAD_FISCAL int NULL,
      ID_RELACION bigint NULL,
      ACCION varchar(24) NOT NULL,
      CAMPOS_JSON nvarchar(max) NOT NULL,
      ACTOR nvarchar(255) NOT NULL,
      FCN_UTC datetime2(7) NOT NULL CONSTRAINT DF_ENTIDAD_FISCAL_AUDIT_UTC DEFAULT(SYSUTCDATETIME()),
      CONSTRAINT FK_ENTIDAD_FISCAL_AUDIT_ENTIDAD FOREIGN KEY(ID_ENTIDAD_FISCAL) REFERENCES dbo.ENTIDAD_FISCAL(ID_ENTIDAD_FISCAL),
      CONSTRAINT FK_ENTIDAD_FISCAL_AUDIT_REL FOREIGN KEY(ID_RELACION) REFERENCES dbo.ENTIDAD_FISCAL_SUCURSAL(ID_RELACION),
      CONSTRAINT CK_ENTIDAD_FISCAL_AUDIT_JSON CHECK(ISJSON(CAMPOS_JSON)=1)
    );

    CREATE INDEX IX_ENTIDAD_FISCAL_SUCURSAL_SUC_VIGENCIA
      ON dbo.ENTIDAD_FISCAL_SUCURSAL(SUC,ESTADO_VALIDACION,VIGENTE_DESDE,VIGENTE_HASTA);
    CREATE INDEX IX_ENTIDAD_FISCAL_SUCURSAL_ENTIDAD
      ON dbo.ENTIDAD_FISCAL_SUCURSAL(ID_ENTIDAD_FISCAL,ESTADO_VALIDACION);
    CREATE UNIQUE INDEX UX_ENTIDAD_FISCAL_SUC_PENDIENTE
      ON dbo.ENTIDAD_FISCAL_SUCURSAL(ID_ENTIDAD_FISCAL,SUC)
      WHERE ESTADO_VALIDACION='PENDIENTE';
    CREATE INDEX IX_ENTIDAD_FISCAL_AUDIT_ENTIDAD
      ON dbo.ENTIDAD_FISCAL_AUDIT(ID_ENTIDAD_FISCAL,FCN_UTC);
  END;

  /* RFC candidates only: never map placeholders, invalid shapes, or generic SAT RFCs. */
  ;WITH SourceRfc AS(
    SELECT DISTINCT UPPER(LTRIM(RTRIM(s.RFC))) RFC
    FROM dbo.DAT_SUC s
    WHERE NULLIF(LTRIM(RTRIM(s.RFC)),N'') IS NOT NULL
  ), Candidate AS(
    SELECT RFC FROM SourceRfc
    WHERE LEN(RFC)=13
      AND RFC COLLATE Latin1_General_100_BIN2 NOT LIKE N'%[^A-Z0-9Ñ&]%'
      AND SUBSTRING(RFC,1,4) COLLATE Latin1_General_100_BIN2 NOT LIKE N'%[^A-ZÑ&]%'
      AND SUBSTRING(RFC,5,6) COLLATE Latin1_General_100_BIN2 NOT LIKE N'%[^0-9]%'
      AND SUBSTRING(RFC,11,3) COLLATE Latin1_General_100_BIN2 NOT LIKE N'%[^A-Z0-9]%'
      AND RFC NOT IN(N'CAMBIO',N'XAXX010101000',N'XEXX010101000')
  )
  INSERT dbo.ENTIDAD_FISCAL(RFC,TIPO_PERSONA,ESTADO_VALIDACION,ORIGEN_CANDIDATO,CREADO_POR,MODIFICADO_POR)
    SELECT c.RFC,'FISICA','PENDIENTE','DAT_SUC.RFC',ORIGINAL_LOGIN(),ORIGINAL_LOGIN()
    FROM Candidate c
    WHERE NOT EXISTS(SELECT 1 FROM dbo.ENTIDAD_FISCAL e WITH(UPDLOCK,HOLDLOCK) WHERE e.RFC=c.RFC);

  ;WITH SourceRfc AS(
    SELECT s.SUC,UPPER(LTRIM(RTRIM(s.RFC))) RFC
    FROM dbo.DAT_SUC s
    WHERE NULLIF(LTRIM(RTRIM(s.RFC)),N'') IS NOT NULL
  )
  INSERT dbo.ENTIDAD_FISCAL_SUCURSAL(ID_ENTIDAD_FISCAL,SUC,ESTADO_VALIDACION,ORIGEN,CREADO_POR,MODIFICADO_POR)
    SELECT e.ID_ENTIDAD_FISCAL,s.SUC,'PENDIENTE','DAT_SUC.RFC',ORIGINAL_LOGIN(),ORIGINAL_LOGIN()
    FROM SourceRfc s
    JOIN dbo.ENTIDAD_FISCAL e ON e.RFC=s.RFC AND e.TIPO_PERSONA='FISICA' AND e.ESTADO_VALIDACION<>'INACTIVA'
    WHERE LEN(s.RFC)=13
      AND s.RFC COLLATE Latin1_General_100_BIN2 NOT LIKE N'%[^A-Z0-9Ñ&]%'
      AND SUBSTRING(s.RFC,1,4) COLLATE Latin1_General_100_BIN2 NOT LIKE N'%[^A-ZÑ&]%'
      AND SUBSTRING(s.RFC,5,6) COLLATE Latin1_General_100_BIN2 NOT LIKE N'%[^0-9]%'
      AND SUBSTRING(s.RFC,11,3) COLLATE Latin1_General_100_BIN2 NOT LIKE N'%[^A-Z0-9]%'
      AND s.RFC NOT IN(N'CAMBIO',N'XAXX010101000',N'XEXX010101000')
      AND NOT EXISTS(SELECT 1 FROM dbo.ENTIDAD_FISCAL_SUCURSAL r WITH(UPDLOCK,HOLDLOCK)
        WHERE r.ID_ENTIDAD_FISCAL=e.ID_ENTIDAD_FISCAL AND r.SUC=s.SUC
          AND (r.ESTADO_VALIDACION='PENDIENTE' OR (r.ESTADO_VALIDACION='VALIDADA' AND r.VIGENTE_HASTA IS NULL)));

  INSERT dbo.ENTIDAD_FISCAL_AUDIT(ID_ENTIDAD_FISCAL,ACCION,CAMPOS_JSON,ACTOR)
    SELECT e.ID_ENTIDAD_FISCAL,'CANDIDATO_IMPORTADO',N'{"source":"DAT_SUC.RFC","state":"PENDIENTE"}',ORIGINAL_LOGIN()
    FROM dbo.ENTIDAD_FISCAL e
    WHERE e.ORIGEN_CANDIDATO='DAT_SUC.RFC'
      AND NOT EXISTS(SELECT 1 FROM dbo.ENTIDAD_FISCAL_AUDIT a WHERE a.ID_ENTIDAD_FISCAL=e.ID_ENTIDAD_FISCAL AND a.ACCION='CANDIDATO_IMPORTADO');

  INSERT dbo.ENTIDAD_FISCAL_AUDIT(ID_ENTIDAD_FISCAL,ID_RELACION,ACCION,CAMPOS_JSON,ACTOR)
    SELECT r.ID_ENTIDAD_FISCAL,r.ID_RELACION,'VINCULO_CANDIDATO',N'{"source":"DAT_SUC.RFC","state":"PENDIENTE"}',ORIGINAL_LOGIN()
    FROM dbo.ENTIDAD_FISCAL_SUCURSAL r
    WHERE r.ORIGEN='DAT_SUC.RFC'
      AND NOT EXISTS(SELECT 1 FROM dbo.ENTIDAD_FISCAL_AUDIT a WHERE a.ID_RELACION=r.ID_RELACION AND a.ACCION='VINCULO_CANDIDATO');

  COMMIT;

  SELECT (SELECT COUNT(*) FROM dbo.ENTIDAD_FISCAL) entidades,
         (SELECT COUNT(*) FROM dbo.ENTIDAD_FISCAL_SUCURSAL) vinculos,
         (SELECT COUNT(*) FROM dbo.ENTIDAD_FISCAL WHERE ESTADO_VALIDACION='PENDIENTE') pendientes,
         (SELECT COUNT(*) FROM dbo.DAT_SUC) sucursales_sin_cambio,
         (SELECT COUNT(*) FROM dbo.EMPRESA) empresas_operativas_sin_cambio;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;
  THROW;
END CATCH;
