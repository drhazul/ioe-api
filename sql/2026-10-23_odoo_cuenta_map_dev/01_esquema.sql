/*
  Odoo account crosswalk, additive development schema only.
  Never changes DAT_CAT_CTAS.CTA, DAT_CTRL_CTAS, Odoo, or financial entries.
  The installer substitutes @Aplicar/@ServidorEsperado only after fresh preflight.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;

DECLARE @Aplicar bit=0,
        @ServidorEsperado nvarchar(128)=NULL,
        @BaseEsperada sysname=N'IOEDESARROLLO';

IF DB_NAME()<>@BaseEsperada
  THROW 53401,'Script exclusivo de IOEDESARROLLO.',1;
IF @@TRANCOUNT<>0
  THROW 53402,'Ejecutar sin transaccion externa.',1;

SELECT @@SERVERNAME servidor,DB_NAME() base,
  CASE WHEN OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP',N'U') IS NULL THEN 0 ELSE 1 END mapa,
  CASE WHEN OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP_AUDIT',N'U') IS NULL THEN 0 ELSE 1 END auditoria;

IF @Aplicar=0 RETURN;
IF @ServidorEsperado IS NULL OR @@SERVERNAME<>@ServidorEsperado OR DB_NAME()<>@BaseEsperada
  THROW 53403,'Destino exacto requerido.',1;
IF OBJECT_ID(N'dbo.ENTIDAD_FISCAL',N'U') IS NULL OR
   OBJECT_ID(N'dbo.DAT_CAT_CTAS',N'U') IS NULL OR
   OBJECT_ID(N'dbo.DAT_SUC',N'U') IS NULL
  THROW 53404,'Faltan tablas base requeridas.',1;

IF NOT EXISTS (
  SELECT 1
  FROM sys.indexes i
  JOIN sys.index_columns ic ON ic.object_id=i.object_id AND ic.index_id=i.index_id
  JOIN sys.columns c ON c.object_id=ic.object_id AND c.column_id=ic.column_id
  WHERE i.object_id=OBJECT_ID(N'dbo.DAT_CAT_CTAS') AND i.is_primary_key=1
    AND ic.key_ordinal=1 AND c.name=N'CTA'
)
  THROW 53405,'DAT_CAT_CTAS.CTA ya no es llave primaria esperada.',1;

DECLARE @Existentes int=
  (CASE WHEN OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP',N'U') IS NULL THEN 0 ELSE 1 END)+
  (CASE WHEN OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP_AUDIT',N'U') IS NULL THEN 0 ELSE 1 END);
IF @Existentes NOT IN (0,2)
  THROW 53406,'Esquema parcial; inspeccionar antes de continuar.',1;

IF @Existentes=2
BEGIN
  IF OBJECT_ID(N'dbo.PK_INT_ODOO_CTA_MAP',N'PK') IS NULL OR
     OBJECT_ID(N'dbo.PK_INT_ODOO_CTA_MAP_AUDIT',N'PK') IS NULL OR
     OBJECT_ID(N'dbo.FK_INT_ODOO_CTA_MAP_ENTIDAD',N'F') IS NULL OR
     OBJECT_ID(N'dbo.FK_INT_ODOO_CTA_MAP_CTA',N'F') IS NULL OR
     OBJECT_ID(N'dbo.FK_INT_ODOO_CTA_MAP_SUC',N'F') IS NULL OR
     OBJECT_ID(N'dbo.FK_INT_ODOO_CTA_MAP_AUDIT_MAPA',N'F') IS NULL OR
     NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP') AND name=N'UX_INT_ODOO_CTA_MAP_GLOBAL') OR
     NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP') AND name=N'UX_INT_ODOO_CTA_MAP_SUC') OR
     NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP') AND name=N'IX_INT_ODOO_CTA_MAP_RESOLVER')
    THROW 53407,'Esquema Odoo crosswalk existente no coincide con version.',1;
  RETURN;
END;

BEGIN TRY
  BEGIN TRAN;

  CREATE TABLE dbo.INT_ODOO_CTA_MAP(
    ID_MAPEO bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_INT_ODOO_CTA_MAP PRIMARY KEY,
    ID_ENTIDAD_FISCAL int NOT NULL,
    CTA_IOE nvarchar(255) NOT NULL,
    SUC nvarchar(10) NULL,
    TIPO_EVENTO nvarchar(64) NOT NULL,
    ROL_APUNTE varchar(24) NOT NULL,
    SIGNO_IMPORTE varchar(12) NOT NULL CONSTRAINT DF_INT_ODOO_CTA_MAP_SIGNO DEFAULT('CUALQUIERA'),
    ODOO_ENTORNO varchar(12) NOT NULL,
    ODOO_COMPANY_ID int NOT NULL,
    ODOO_COD_CUENTA nvarchar(64) NOT NULL,
    ESTADO_MAPEO varchar(12) NOT NULL CONSTRAINT DF_INT_ODOO_CTA_MAP_ESTADO DEFAULT('PENDIENTE'),
    APROBADO_POR nvarchar(255) NULL,
    REFERENCIA_APROBACION nvarchar(250) NULL,
    FCN_APROBACION_UTC datetime2(7) NULL,
    CREADO_POR nvarchar(255) NOT NULL,
    FCN_CREACION_UTC datetime2(7) NOT NULL CONSTRAINT DF_INT_ODOO_CTA_MAP_CREACION DEFAULT(SYSUTCDATETIME()),
    MODIFICADO_POR nvarchar(255) NOT NULL,
    FCN_MODIFICACION_UTC datetime2(7) NOT NULL CONSTRAINT DF_INT_ODOO_CTA_MAP_MODIFICACION DEFAULT(SYSUTCDATETIME()),
    VERSION rowversion NOT NULL,
    CONSTRAINT FK_INT_ODOO_CTA_MAP_ENTIDAD FOREIGN KEY(ID_ENTIDAD_FISCAL)
      REFERENCES dbo.ENTIDAD_FISCAL(ID_ENTIDAD_FISCAL),
    CONSTRAINT FK_INT_ODOO_CTA_MAP_CTA FOREIGN KEY(CTA_IOE)
      REFERENCES dbo.DAT_CAT_CTAS(CTA),
    CONSTRAINT FK_INT_ODOO_CTA_MAP_SUC FOREIGN KEY(SUC)
      REFERENCES dbo.DAT_SUC(SUC),
    CONSTRAINT CK_INT_ODOO_CTA_MAP_EVENTO CHECK(LEN(LTRIM(RTRIM(TIPO_EVENTO)))>0),
    CONSTRAINT CK_INT_ODOO_CTA_MAP_ROL CHECK(ROL_APUNTE IN('PRINCIPAL','DEBE','HABER','CONTRAPARTIDA')),
    CONSTRAINT CK_INT_ODOO_CTA_MAP_SIGNO CHECK(SIGNO_IMPORTE IN('CUALQUIERA','POSITIVO','NEGATIVO')),
    CONSTRAINT CK_INT_ODOO_CTA_MAP_ENTORNO CHECK(ODOO_ENTORNO IN('ONLINE','LOCAL')),
    CONSTRAINT CK_INT_ODOO_CTA_MAP_COMPANY CHECK(ODOO_COMPANY_ID>0),
    CONSTRAINT CK_INT_ODOO_CTA_MAP_CODIGO CHECK(LEN(LTRIM(RTRIM(ODOO_COD_CUENTA)))>0),
    CONSTRAINT CK_INT_ODOO_CTA_MAP_ESTADO CHECK(ESTADO_MAPEO IN('PENDIENTE','VALIDADA','INACTIVA')),
    CONSTRAINT CK_INT_ODOO_CTA_MAP_APROBACION CHECK(ESTADO_MAPEO<>'VALIDADA' OR
      (APROBADO_POR IS NOT NULL AND REFERENCIA_APROBACION IS NOT NULL AND FCN_APROBACION_UTC IS NOT NULL))
  );

  CREATE UNIQUE INDEX UX_INT_ODOO_CTA_MAP_GLOBAL
    ON dbo.INT_ODOO_CTA_MAP(ODOO_ENTORNO,ID_ENTIDAD_FISCAL,CTA_IOE,TIPO_EVENTO,ROL_APUNTE,SIGNO_IMPORTE)
    WHERE SUC IS NULL;
  CREATE UNIQUE INDEX UX_INT_ODOO_CTA_MAP_SUC
    ON dbo.INT_ODOO_CTA_MAP(ODOO_ENTORNO,ID_ENTIDAD_FISCAL,CTA_IOE,SUC,TIPO_EVENTO,ROL_APUNTE,SIGNO_IMPORTE)
    WHERE SUC IS NOT NULL;
  CREATE INDEX IX_INT_ODOO_CTA_MAP_RESOLVER
    ON dbo.INT_ODOO_CTA_MAP(ODOO_ENTORNO,ID_ENTIDAD_FISCAL,CTA_IOE,ESTADO_MAPEO)
    INCLUDE(SUC,TIPO_EVENTO,ROL_APUNTE,SIGNO_IMPORTE,ODOO_COMPANY_ID,ODOO_COD_CUENTA);

  CREATE TABLE dbo.INT_ODOO_CTA_MAP_AUDIT(
    ID_AUDIT bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_INT_ODOO_CTA_MAP_AUDIT PRIMARY KEY,
    ID_MAPEO bigint NOT NULL,
    ACCION varchar(24) NOT NULL,
    CAMPOS_JSON nvarchar(max) NOT NULL,
    ACTOR nvarchar(255) NOT NULL,
    FCN_UTC datetime2(7) NOT NULL CONSTRAINT DF_INT_ODOO_CTA_MAP_AUDIT_UTC DEFAULT(SYSUTCDATETIME()),
    CONSTRAINT FK_INT_ODOO_CTA_MAP_AUDIT_MAPA FOREIGN KEY(ID_MAPEO)
      REFERENCES dbo.INT_ODOO_CTA_MAP(ID_MAPEO),
    CONSTRAINT CK_INT_ODOO_CTA_MAP_AUDIT_JSON CHECK(ISJSON(CAMPOS_JSON)=1)
  );
  CREATE INDEX IX_INT_ODOO_CTA_MAP_AUDIT_MAPA
    ON dbo.INT_ODOO_CTA_MAP_AUDIT(ID_MAPEO,FCN_UTC);

  COMMIT;

  SELECT @@SERVERNAME servidor,DB_NAME() base,
    (SELECT COUNT(*) FROM dbo.INT_ODOO_CTA_MAP) mapeos,
    (SELECT COUNT(*) FROM dbo.INT_ODOO_CTA_MAP_AUDIT) auditorias,
    N'CTA IOE y movimientos sin cambio; sin cuentas Odoo ni asientos' alcance;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;
  THROW;
END CATCH;
