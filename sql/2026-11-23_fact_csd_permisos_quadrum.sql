/* Preparación estructural. Inicialización de permisos se ejecuta por separado
   con matriz verificada del ambiente y respaldo de valores. */
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID('dbo.FACT_CSD','U') IS NULL THROW 51000, 'FACT_CSD no existe', 1;
IF COL_LENGTH('dbo.FACT_CSD','QUADRUM_FACTURA_HABILITADA') IS NULL
  ALTER TABLE dbo.FACT_CSD ADD QUADRUM_FACTURA_HABILITADA bit NOT NULL
    CONSTRAINT DF_CSD_QUADRUM_FACTURA DEFAULT 0 WITH VALUES;
IF COL_LENGTH('dbo.FACT_CSD','QUADRUM_NOTA_CREDITO_HABILITADA') IS NULL
  ALTER TABLE dbo.FACT_CSD ADD QUADRUM_NOTA_CREDITO_HABILITADA bit NOT NULL
    CONSTRAINT DF_CSD_QUADRUM_NC DEFAULT 0 WITH VALUES;
IF COL_LENGTH('dbo.FACT_CSD','QUADRUM_COMPLEMENTO_PAGO_HABILITADO') IS NULL
  ALTER TABLE dbo.FACT_CSD ADD QUADRUM_COMPLEMENTO_PAGO_HABILITADO bit NOT NULL
    CONSTRAINT DF_CSD_QUADRUM_PAGO DEFAULT 0 WITH VALUES;
IF COL_LENGTH('dbo.FACT_CSD','QUADRUM_PERMISOS_USUARIO') IS NULL
  ALTER TABLE dbo.FACT_CSD ADD QUADRUM_PERMISOS_USUARIO nvarchar(120) NULL;
IF COL_LENGTH('dbo.FACT_CSD','QUADRUM_PERMISOS_FECHA') IS NULL
  ALTER TABLE dbo.FACT_CSD ADD QUADRUM_PERMISOS_FECHA datetime2 NULL;
COMMIT TRANSACTION;
