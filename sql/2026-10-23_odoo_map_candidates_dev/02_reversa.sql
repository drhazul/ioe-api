/* Reverses only unchanged PENDIENTE proposals from IOE-ODOO-MAP-20261023. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;

DECLARE @Aplicar bit=0,
        @ServidorEsperado sysname=N'dd7842d7ba7e',
        @BaseEsperada sysname=N'IOEDESARROLLO',
        @Cambio nvarchar(64)=N'IOE-ODOO-MAP-20261023',
        @Actor nvarchar(255)=N'CODEX-ODOO-MAP-20261023';
IF DB_NAME()<>@BaseEsperada OR @@SERVERNAME<>@ServidorEsperado
  THROW 53521,'Destino distinto de IOEDESARROLLO autorizado.',1;
IF @@TRANCOUNT<>0
  THROW 53522,'Ejecutar sin transaccion externa.',1;

DECLARE @Eventos table(
  CTA_IOE nvarchar(255) NOT NULL,
  TIPO_EVENTO nvarchar(64) NOT NULL,
  SIGNO_IMPORTE varchar(12) NOT NULL,
  ODOO_COD_CUENTA nvarchar(64) NOT NULL
);
