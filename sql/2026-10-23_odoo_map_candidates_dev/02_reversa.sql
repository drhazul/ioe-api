DECLARE @Entidades table(ID_ENTIDAD_FISCAL int,ODOO_COMPANY_ID int);
INSERT @Entidades VALUES(1,1),(2,2),(3,3);
DECLARE @Objetivos table(
  ID_ENTIDAD_FISCAL int,ODOO_COMPANY_ID int,CTA_IOE nvarchar(255),
  TIPO_EVENTO nvarchar(64),ROL_APUNTE varchar(24),SIGNO_IMPORTE varchar(12),
  ODOO_COD_CUENTA nvarchar(64)
);
INSERT @Objetivos
SELECT e.ID_ENTIDAD_FISCAL,e.ODOO_COMPANY_ID,v.CTA_IOE,v.TIPO_EVENTO,
       'PRINCIPAL',v.SIGNO_IMPORTE,v.ODOO_COD_CUENTA
FROM @Entidades e CROSS JOIN @Eventos v;

DECLARE @Encontradas int=(
  SELECT COUNT(*) FROM dbo.INT_ODOO_CTA_MAP m JOIN @Objetivos p
    ON m.ODOO_ENTORNO='ONLINE' AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL
   AND m.CTA_IOE=p.CTA_IOE AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
   AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
   AND m.ODOO_COMPANY_ID=p.ODOO_COMPANY_ID AND m.ODOO_COD_CUENTA=p.ODOO_COD_CUENTA
   AND m.ESTADO_MAPEO='PENDIENTE' AND m.CREADO_POR=@Actor
   AND m.APROBADO_POR IS NULL AND m.REFERENCIA_APROBACION IS NULL
);
IF @Encontradas NOT IN(0,33)
  THROW 53523,'Reversa parcial o filas cambiadas; revisar manualmente.',1;
IF @Encontradas=33 AND EXISTS(
  SELECT 1 FROM dbo.INT_ODOO_CTA_MAP m JOIN @Objetivos p
    ON m.ODOO_ENTORNO='ONLINE' AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL
   AND m.CTA_IOE=p.CTA_IOE AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
   AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  WHERE m.ODOO_COMPANY_ID<>p.ODOO_COMPANY_ID OR m.ODOO_COD_CUENTA<>p.ODOO_COD_CUENTA OR
        m.ESTADO_MAPEO<>'PENDIENTE' OR m.CREADO_POR<>@Actor OR
        m.APROBADO_POR IS NOT NULL OR m.REFERENCIA_APROBACION IS NOT NULL OR
        (SELECT COUNT(*) FROM dbo.INT_ODOO_CTA_MAP_AUDIT a WHERE a.ID_MAPEO=m.ID_MAPEO)<>1 OR
        NOT EXISTS(SELECT 1 FROM dbo.INT_ODOO_CTA_MAP_AUDIT a
          WHERE a.ID_MAPEO=m.ID_MAPEO AND a.ACCION='PROPUESTA_PENDIENTE'
            AND JSON_VALUE(a.CAMPOS_JSON,'$.cambio')=@Cambio AND a.ACTOR=@Actor)
)
  THROW 53524,'Hay auditoria posterior o modificacion; preservar el historial.',1;

IF @Aplicar=0
BEGIN
  SELECT @@SERVERNAME servidor,DB_NAME() base,@Encontradas filas_reversibles,
    N'No borrar si una propuesta fue aprobada o auditada después' alcance;
  RETURN;
END;
IF @Encontradas=0
BEGIN
  SELECT @@SERVERNAME servidor,DB_NAME() base,0 filas_reversibles,N'Sin cambios' alcance;
  RETURN;
END;

BEGIN TRY
  BEGIN TRAN;
  DELETE a
  FROM dbo.INT_ODOO_CTA_MAP_AUDIT a
  JOIN dbo.INT_ODOO_CTA_MAP m ON m.ID_MAPEO=a.ID_MAPEO
  JOIN @Objetivos p ON m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL
    AND m.CTA_IOE=p.CTA_IOE AND m.TIPO_EVENTO=p.TIPO_EVENTO
    AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  WHERE m.ODOO_ENTORNO='ONLINE' AND m.SUC IS NULL AND a.ACCION='PROPUESTA_PENDIENTE'
    AND JSON_VALUE(a.CAMPOS_JSON,'$.cambio')=@Cambio AND a.ACTOR=@Actor;

  DELETE m
  FROM dbo.INT_ODOO_CTA_MAP m
  JOIN @Objetivos p ON m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL
    AND m.CTA_IOE=p.CTA_IOE AND m.TIPO_EVENTO=p.TIPO_EVENTO
    AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  WHERE m.ODOO_ENTORNO='ONLINE' AND m.SUC IS NULL AND m.ESTADO_MAPEO='PENDIENTE'
    AND m.CREADO_POR=@Actor AND m.ODOO_COMPANY_ID=p.ODOO_COMPANY_ID
    AND m.ODOO_COD_CUENTA=p.ODOO_COD_CUENTA;
  COMMIT;
  SELECT @@SERVERNAME servidor,DB_NAME() base,
    (SELECT COUNT(*) FROM dbo.INT_ODOO_CTA_MAP m JOIN @Objetivos p
      ON m.ODOO_ENTORNO='ONLINE' AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL
      AND m.CTA_IOE=p.CTA_IOE AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
      AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE) restantes,
    N'Reversa aplicada; sin cambios a cuentas fuente u Odoo' alcance;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;
  THROW;
END CATCH;
