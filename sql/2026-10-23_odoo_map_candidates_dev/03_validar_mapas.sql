DECLARE @Entidades table(ID_ENTIDAD_FISCAL int NOT NULL,ODOO_COMPANY_ID int NOT NULL);
INSERT @Entidades VALUES(1,1),(2,2),(3,3);
DECLARE @Esperadas table(
  ID_ENTIDAD_FISCAL int NOT NULL,ODOO_COMPANY_ID int NOT NULL,
  CTA_IOE nvarchar(255) NOT NULL,TIPO_EVENTO nvarchar(64) NOT NULL,
  ROL_APUNTE varchar(24) NOT NULL,SIGNO_IMPORTE varchar(12) NOT NULL,
  ODOO_COD_CUENTA nvarchar(64) NOT NULL,CMOV int NOT NULL
);
INSERT @Esperadas
SELECT e.ID_ENTIDAD_FISCAL,e.ODOO_COMPANY_ID,v.CTA_IOE,v.TIPO_EVENTO,
       'PRINCIPAL',v.SIGNO_IMPORTE,v.ODOO_COD_CUENTA,v.CMOV
FROM @Entidades e CROSS JOIN @Eventos v;

IF (SELECT COUNT(*) FROM @Esperadas)<>33 OR
   (SELECT COUNT_BIG(*) FROM dbo.INT_ODOO_CTA_MAP)<>33 OR
   (SELECT COUNT_BIG(*) FROM dbo.INT_ODOO_CTA_MAP_AUDIT)<>33
  THROW 53534,'Conteos de crosswalk/auditoria distintos de 33; no aprobar.',1;
IF (SELECT COUNT_BIG(*) FROM dbo.ENTIDAD_FISCAL)<>3 OR
   (SELECT COUNT_BIG(*) FROM dbo.ENTIDAD_FISCAL_SUCURSAL)<>10 OR
   EXISTS(SELECT 1 FROM dbo.ENTIDAD_FISCAL WHERE ESTADO_VALIDACION<>'PENDIENTE') OR
   EXISTS(SELECT 1 FROM dbo.ENTIDAD_FISCAL_SUCURSAL WHERE ESTADO_VALIDACION<>'PENDIENTE')
  THROW 53535,'Cambió estado/conjunto fiscal o sucursales; repetir preflight.',1;
IF (SELECT COUNT_BIG(*) FROM dbo.DAT_CAT_CTAS)<>7 OR
   (SELECT COUNT_BIG(*) FROM dbo.DAT_CTRL_CTAS)<>34457
  THROW 53536,'Cambió catálogo/movimientos fuente; revisar antes de aprobar.',1;
IF EXISTS(
  SELECT 1 FROM @Esperadas p
  LEFT JOIN dbo.INT_ODOO_CTA_MAP m WITH(UPDLOCK,HOLDLOCK)
    ON m.ODOO_ENTORNO='ONLINE' AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL
   AND m.CTA_IOE=p.CTA_IOE AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
   AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  WHERE m.ID_MAPEO IS NULL OR m.ODOO_COMPANY_ID<>p.ODOO_COMPANY_ID OR
        m.ODOO_COD_CUENTA<>p.ODOO_COD_CUENTA OR m.ESTADO_MAPEO<>'PENDIENTE' OR
        m.CREADO_POR<>N'CODEX-ODOO-MAP-20261023' OR m.APROBADO_POR IS NOT NULL OR
        m.REFERENCIA_APROBACION IS NOT NULL OR m.FCN_APROBACION_UTC IS NOT NULL OR
        (SELECT COUNT_BIG(*) FROM dbo.INT_ODOO_CTA_MAP_AUDIT a WHERE a.ID_MAPEO=m.ID_MAPEO)<>1 OR
        NOT EXISTS(
          SELECT 1 FROM dbo.INT_ODOO_CTA_MAP_AUDIT a
          WHERE a.ID_MAPEO=m.ID_MAPEO AND a.ACCION='PROPUESTA_PENDIENTE'
            AND a.ACTOR=N'CODEX-ODOO-MAP-20261023'
            AND JSON_VALUE(a.CAMPOS_JSON,'$.cambio')=N'IOE-ODOO-MAP-20261023'
        )
)
  THROW 53537,'Una propuesta cambió o su auditoría no coincide; no aprobar.',1;
IF EXISTS(
  SELECT 1 FROM dbo.INT_ODOO_CTA_MAP m
  LEFT JOIN @Esperadas p ON m.ODOO_ENTORNO='ONLINE'
   AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL AND m.CTA_IOE=p.CTA_IOE
   AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
   AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  WHERE p.ID_ENTIDAD_FISCAL IS NULL
)
  THROW 53538,'Hay mapas fuera de la lista aprobada; no aprobar.',1;

IF @Aplicar=0
BEGIN
  SELECT @@SERVERNAME servidor,DB_NAME() base,COUNT(*) propuestas,
    N'Lista exacta preparada; aprobación contable confirmada por titular; fichas fiscales/vínculos siguen PENDIENTE' alcance
  FROM @Esperadas;
  RETURN;
END;

BEGIN TRY
  BEGIN TRAN;
  DECLARE @Aprobadas table(ID_MAPEO bigint NOT NULL,ESTADO_ANTERIOR varchar(12),ESTADO_NUEVO varchar(12));
  UPDATE m WITH(UPDLOCK,HOLDLOCK)
    SET ESTADO_MAPEO='VALIDADA',APROBADO_POR=@Aprobador,
        REFERENCIA_APROBACION=@Referencia,FCN_APROBACION_UTC=SYSUTCDATETIME(),
        MODIFICADO_POR=@Actor,FCN_MODIFICACION_UTC=SYSUTCDATETIME()
  OUTPUT inserted.ID_MAPEO,deleted.ESTADO_MAPEO,inserted.ESTADO_MAPEO
    INTO @Aprobadas(ID_MAPEO,ESTADO_ANTERIOR,ESTADO_NUEVO)
  FROM dbo.INT_ODOO_CTA_MAP m
  JOIN @Esperadas p ON m.ODOO_ENTORNO='ONLINE'
    AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL AND m.CTA_IOE=p.CTA_IOE
    AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
    AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  WHERE m.ESTADO_MAPEO='PENDIENTE' AND m.APROBADO_POR IS NULL;

  IF (SELECT COUNT(*) FROM @Aprobadas)<>33
    THROW 53539,'No se actualizaron exactamente 33 propuestas; revertir transaccion.',1;

  INSERT dbo.INT_ODOO_CTA_MAP_AUDIT(ID_MAPEO,ACCION,CAMPOS_JSON,ACTOR)
  SELECT a.ID_MAPEO,'VALIDADA',
    (SELECT @Cambio AS cambio,a.ESTADO_ANTERIOR AS estadoAnterior,
      a.ESTADO_NUEVO AS estadoNuevo,@Aprobador AS aprobador,@Referencia AS referencia,
      N'No habilita sincronizacion mientras identidad fiscal o sucursal sigan pendientes' AS limite
     FOR JSON PATH,WITHOUT_ARRAY_WRAPPER),@Actor
  FROM @Aprobadas a;

  IF EXISTS(
    SELECT 1 FROM dbo.INT_ODOO_CTA_MAP m JOIN @Esperadas p
      ON m.ODOO_ENTORNO='ONLINE' AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL
     AND m.CTA_IOE=p.CTA_IOE AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
     AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
    WHERE m.ESTADO_MAPEO<>'VALIDADA' OR m.APROBADO_POR<>@Aprobador OR
      m.REFERENCIA_APROBACION<>@Referencia OR m.FCN_APROBACION_UTC IS NULL OR
      (SELECT COUNT_BIG(*) FROM dbo.INT_ODOO_CTA_MAP_AUDIT a WHERE a.ID_MAPEO=m.ID_MAPEO)<>2 OR
      NOT EXISTS(SELECT 1 FROM dbo.INT_ODOO_CTA_MAP_AUDIT a WHERE a.ID_MAPEO=m.ID_MAPEO
        AND a.ACCION='VALIDADA' AND JSON_VALUE(a.CAMPOS_JSON,'$.cambio')=@Cambio AND a.ACTOR=@Actor)
  )
    THROW 53540,'Postvalidacion de mapas/auditoria falló; revertir transaccion.',1;

  COMMIT;
  SELECT @@SERVERNAME servidor,DB_NAME() base,(SELECT COUNT(*) FROM @Aprobadas) aprobadas,
    (SELECT COUNT_BIG(*) FROM dbo.INT_ODOO_CTA_MAP WHERE ESTADO_MAPEO='VALIDADA') total_validadas,
    (SELECT COUNT_BIG(*) FROM dbo.ENTIDAD_FISCAL WHERE ESTADO_VALIDACION='PENDIENTE') entidades_fiscales_pendientes,
    (SELECT COUNT_BIG(*) FROM dbo.ENTIDAD_FISCAL_SUCURSAL WHERE ESTADO_VALIDACION='PENDIENTE') vinculos_pendientes,
    N'Solo se valida crosswalk; sin contabilizacion Odoo' alcance;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;
  THROW;
END CATCH;
