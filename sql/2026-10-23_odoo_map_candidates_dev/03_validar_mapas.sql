/* Approve only the 33 reviewed account crosswalks in IOEDESARROLLO. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;

DECLARE @Aplicar bit=0,
        @ServidorEsperado sysname=N'dd7842d7ba7e',
        @BaseEsperada sysname=N'IOEDESARROLLO',
        @Cambio nvarchar(64)=N'IOE-ODOO-MAP-APPROVAL-20261023',
        @Actor nvarchar(255)=N'CODEX-ODOO-MAP-APPROVAL-20261023',
        @Aprobador nvarchar(255)=N'TITULAR IOE (autorizacion contable confirmada)',
        @Referencia nvarchar(250)=N'Autorizacion contable confirmada por titular en conversacion, 2026-10-23';

IF DB_NAME()<>@BaseEsperada OR @@SERVERNAME<>@ServidorEsperado
  THROW 53531,'Destino distinto de IOEDESARROLLO autorizado.',1;
IF @@TRANCOUNT<>0
  THROW 53532,'Ejecutar sin transaccion externa.',1;
IF OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP',N'U') IS NULL OR
   OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP_AUDIT',N'U') IS NULL
  THROW 53533,'Falta el esquema de equivalencias.',1;

DECLARE @Eventos table(
  CTA_IOE nvarchar(255) NOT NULL,
  TIPO_EVENTO nvarchar(64) NOT NULL,
  SIGNO_IMPORTE varchar(12) NOT NULL,
  ODOO_COMPANY_ID int NOT NULL,
  ODOO_COD_CUENTA nvarchar(64) NOT NULL,
  CMOV int NOT NULL
);
INSERT @Eventos VALUES
