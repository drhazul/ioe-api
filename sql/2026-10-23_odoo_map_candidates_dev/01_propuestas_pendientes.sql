  (N'101001002',601,N'CREDITO_CLIENTE_ABONO','POSITIVO',N'105.01.01'),
  (N'101001002',601,N'CREDITO_CLIENTE_ABONO','NEGATIVO',N'105.01.01'),
  (N'101001002',602,N'CREDITO_CLIENTE_CARGO','NEGATIVO',N'105.01.01'),
  (N'101001003',912,N'CAJA_CHICA_DISPOSICION_REINTEGRO','POSITIVO',N'101.01.01'),
  (N'210001019',611,N'APARTADO_CLIENTE_ABONO','POSITIVO',N'206.01.01'),
