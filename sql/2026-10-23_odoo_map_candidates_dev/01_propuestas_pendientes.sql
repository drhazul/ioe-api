DECLARE @Propuestas table(
  ID_ENTIDAD_FISCAL int NOT NULL,
  CTA_IOE nvarchar(255) NOT NULL,
  TIPO_EVENTO nvarchar(64) NOT NULL,
  ROL_APUNTE varchar(24) NOT NULL,
  SIGNO_IMPORTE varchar(12) NOT NULL,
  ODOO_COMPANY_ID int NOT NULL,
  ODOO_COD_CUENTA nvarchar(64) NOT NULL,
  CMOV int NOT NULL,
  PRIMARY KEY(ID_ENTIDAD_FISCAL,CTA_IOE,TIPO_EVENTO,ROL_APUNTE,SIGNO_IMPORTE)
);
INSERT @Propuestas
SELECT e.ID_ENTIDAD_FISCAL,v.CTA_IOE,v.TIPO_EVENTO,'PRINCIPAL',v.SIGNO_IMPORTE,
       e.ODOO_COMPANY_ID,v.ODOO_COD_CUENTA,v.CMOV
FROM @Entidades e CROSS JOIN @Eventos v;

IF (SELECT COUNT(*) FROM @Propuestas)<>33
  THROW 53504,'La lista de propuestas no coincide con las 33 filas esperadas.',1;
IF EXISTS(
  SELECT 1 FROM @Entidades e
  LEFT JOIN dbo.ENTIDAD_FISCAL f ON f.ID_ENTIDAD_FISCAL=e.ID_ENTIDAD_FISCAL
  WHERE f.ID_ENTIDAD_FISCAL IS NULL OR f.NOMBRE_LEGAL<>e.NOMBRE_LEGAL OR
        f.ESTADO_VALIDACION<>'PENDIENTE'
)
  THROW 53505,'Entidad fiscal cambió o no coincide con compañía Odoo verificada.',1;
IF (SELECT COUNT(*) FROM dbo.ENTIDAD_FISCAL_SUCURSAL)<>10 OR
   EXISTS(SELECT 1 FROM dbo.ENTIDAD_FISCAL_SUCURSAL WHERE ESTADO_VALIDACION<>'PENDIENTE')
  THROW 53506,'Cambió el conjunto/estado de vínculos sucursal-entidad; repetir preflight.',1;

IF EXISTS(
  SELECT 1 FROM (VALUES
    (N'101001001',N'DIFERENCIAS EN ORD DE TRABAJO',N'AD'),
    (N'101001002',N'CREDITO A CLIENTES',N'CR'),
    (N'101001003',N'CAJA CHICA',N'DC'),
    (N'210001019',N'BONO DE APARTADO',N'AP'),
    (N'704010003',N'FALTANTES Y SOBRANTES',NULL),
    (N'704010004',N'GASTOS VARIOS',N'DG')
  ) v(CTA,DCTA,RELACION)
  LEFT JOIN dbo.DAT_CAT_CTAS c ON c.CTA=v.CTA
  WHERE c.CTA IS NULL OR UPPER(LTRIM(RTRIM(c.DCTA)))<>v.DCTA OR
        ISNULL(c.RELACION,N'')<>ISNULL(v.RELACION,N'') OR c.SUC IS NOT NULL
)
  THROW 53507,'Catalogo fuente cambió; repetir preflight antes de mapear.',1;

IF EXISTS(
  SELECT 1 FROM dbo.DAT_CTRL_CTAS c
  WHERE c.CTA IN(N'101001001',N'101001002',N'101001003',N'210001019',N'704010003',N'704010004')
    AND TRY_CONVERT(int,c.CLSD) NOT IN(0,601,602,611,612,801,802,901,902,912,914)
)
  THROW 53508,'Hay clases de movimiento sin candidato; revisar y no aplicar lote.',1;

IF EXISTS(
  SELECT 1 FROM @Eventos e
  WHERE NOT EXISTS(
    SELECT 1 FROM dbo.DAT_CTRL_CTAS c
    WHERE c.CTA=e.CTA_IOE AND TRY_CONVERT(int,c.CLSD)=e.CMOV
      AND ((e.SIGNO_IMPORTE='POSITIVO' AND c.IMPT>0) OR
           (e.SIGNO_IMPORTE='NEGATIVO' AND c.IMPT<0) OR
           (e.CMOV=601 AND e.SIGNO_IMPORTE='NEGATIVO' AND c.IMPT<0))
  )
)
  THROW 53509,'Falta evidencia de clase/signo para una propuesta; revisar fuente.',1;

IF EXISTS(
  SELECT 1 FROM @Propuestas p
  JOIN dbo.INT_ODOO_CTA_MAP m ON m.ODOO_ENTORNO='ONLINE'
    AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL AND m.CTA_IOE=p.CTA_IOE
    AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
    AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  WHERE m.ODOO_COMPANY_ID<>p.ODOO_COMPANY_ID OR m.ODOO_COD_CUENTA<>p.ODOO_COD_CUENTA OR
        m.ESTADO_MAPEO<>'PENDIENTE' OR m.CREADO_POR<>@Actor OR
        m.APROBADO_POR IS NOT NULL OR m.REFERENCIA_APROBACION IS NOT NULL
)
  THROW 53510,'Existe equivalencia previa distinta o ya aprobada; no sobrescribir.',1;

IF @Aplicar=0
BEGIN
  SELECT @@SERVERNAME servidor,DB_NAME() base,COUNT(*) propuestas,
    N'PENDIENTE; sin cuentas Odoo nuevas ni asientos; sin cambio de CTA IOE' alcance
  FROM @Propuestas;
  RETURN;
END;

BEGIN TRY
  BEGIN TRAN;
  DECLARE @Insertadas table(
    ID_MAPEO bigint NOT NULL,
    ID_ENTIDAD_FISCAL int NOT NULL,
    CTA_IOE nvarchar(255) NOT NULL,
    TIPO_EVENTO nvarchar(64) NOT NULL,
    ROL_APUNTE varchar(24) NOT NULL,
    SIGNO_IMPORTE varchar(12) NOT NULL
  );

  INSERT dbo.INT_ODOO_CTA_MAP(
    ID_ENTIDAD_FISCAL,CTA_IOE,SUC,TIPO_EVENTO,ROL_APUNTE,SIGNO_IMPORTE,
    ODOO_ENTORNO,ODOO_COMPANY_ID,ODOO_COD_CUENTA,ESTADO_MAPEO,
    APROBADO_POR,REFERENCIA_APROBACION,FCN_APROBACION_UTC,CREADO_POR,MODIFICADO_POR
  )
  OUTPUT inserted.ID_MAPEO,inserted.ID_ENTIDAD_FISCAL,inserted.CTA_IOE,
         inserted.TIPO_EVENTO,inserted.ROL_APUNTE,inserted.SIGNO_IMPORTE
    INTO @Insertadas
  SELECT p.ID_ENTIDAD_FISCAL,p.CTA_IOE,NULL,p.TIPO_EVENTO,p.ROL_APUNTE,p.SIGNO_IMPORTE,
         'ONLINE',p.ODOO_COMPANY_ID,p.ODOO_COD_CUENTA,'PENDIENTE',
         NULL,NULL,NULL,@Actor,@Actor
  FROM @Propuestas p
  WHERE NOT EXISTS(
    SELECT 1 FROM dbo.INT_ODOO_CTA_MAP m
    WHERE m.ODOO_ENTORNO='ONLINE' AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL
      AND m.CTA_IOE=p.CTA_IOE AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
      AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  );

  INSERT dbo.INT_ODOO_CTA_MAP_AUDIT(ID_MAPEO,ACCION,CAMPOS_JSON,ACTOR)
  SELECT i.ID_MAPEO,'PROPUESTA_PENDIENTE',
    (SELECT p.ID_ENTIDAD_FISCAL AS entidadFiscal,p.ODOO_COMPANY_ID AS companyOdoo,
            p.CTA_IOE AS cuentaIoe,p.CMOV AS claseMovimiento,p.TIPO_EVENTO AS evento,
            p.SIGNO_IMPORTE AS signoImpt,p.ODOO_COD_CUENTA AS cuentaOdoo,
            N'PENDIENTE' AS estado,@Cambio AS cambio,
            N'Revision contable y sucursal-entidad pendiente; no contabilizar' AS nota
     FOR JSON PATH,WITHOUT_ARRAY_WRAPPER),
    @Actor
  FROM @Insertadas i
  JOIN @Propuestas p ON p.ID_ENTIDAD_FISCAL=i.ID_ENTIDAD_FISCAL AND p.CTA_IOE=i.CTA_IOE
    AND p.TIPO_EVENTO=i.TIPO_EVENTO AND p.ROL_APUNTE=i.ROL_APUNTE
    AND p.SIGNO_IMPORTE=i.SIGNO_IMPORTE;

  IF EXISTS(
    SELECT 1 FROM @Propuestas p
    LEFT JOIN dbo.INT_ODOO_CTA_MAP m ON m.ODOO_ENTORNO='ONLINE'
      AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL AND m.CTA_IOE=p.CTA_IOE
      AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
      AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
    WHERE m.ID_MAPEO IS NULL OR m.ODOO_COMPANY_ID<>p.ODOO_COMPANY_ID OR
      m.ODOO_COD_CUENTA<>p.ODOO_COD_CUENTA OR m.ESTADO_MAPEO<>'PENDIENTE' OR
      m.CREADO_POR<>@Actor OR m.APROBADO_POR IS NOT NULL OR
      m.REFERENCIA_APROBACION IS NOT NULL OR NOT EXISTS(
        SELECT 1 FROM dbo.INT_ODOO_CTA_MAP_AUDIT a
        WHERE a.ID_MAPEO=m.ID_MAPEO AND a.ACCION='PROPUESTA_PENDIENTE'
          AND JSON_VALUE(a.CAMPOS_JSON,'$.cambio')=@Cambio
      )
  )
    THROW 53511,'Postvalidacion de propuestas/auditoria falló; revertir transaccion.',1;

  COMMIT;
  SELECT @@SERVERNAME servidor,DB_NAME() base,
    (SELECT COUNT(*) FROM @Insertadas) nuevas,
    (SELECT COUNT(*) FROM dbo.INT_ODOO_CTA_MAP m JOIN @Propuestas p
      ON m.ODOO_ENTORNO='ONLINE' AND m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL
      AND m.CTA_IOE=p.CTA_IOE AND m.SUC IS NULL AND m.TIPO_EVENTO=p.TIPO_EVENTO
      AND m.ROL_APUNTE=p.ROL_APUNTE AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
      WHERE m.ESTADO_MAPEO='PENDIENTE') total_pendientes,
    (SELECT COUNT(*) FROM dbo.INT_ODOO_CTA_MAP_AUDIT a
      WHERE a.ACCION='PROPUESTA_PENDIENTE' AND JSON_VALUE(a.CAMPOS_JSON,'$.cambio')=@Cambio) auditorias,
    N'No se creó cuenta Odoo ni asiento; DAT_CAT_CTAS.CTA intacta' alcance;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;
  THROW;
END CATCH;
