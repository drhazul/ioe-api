/*
  Proposals only. Never changes DAT_CAT_CTAS.CTA, DAT_CTRL_CTAS, Odoo, or entries.
  Runner changes @Aplicar only after fresh SQL + Odoo preflight and verified backup.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;

DECLARE @Aplicar bit=0,
        @ServidorEsperado sysname=N'dd7842d7ba7e',
        @BaseEsperada sysname=N'IOEDESARROLLO',
        @Cambio nvarchar(64)=N'IOE-ODOO-MAP-20261023',
        @Actor nvarchar(255)=N'CODEX-ODOO-MAP-20261023';

IF DB_NAME()<>@BaseEsperada OR @@SERVERNAME<>@ServidorEsperado
  THROW 53501,'Destino distinto de IOEDESARROLLO autorizado.',1;
IF @@TRANCOUNT<>0
  THROW 53502,'Ejecutar sin transaccion externa.',1;
IF OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP',N'U') IS NULL OR
   OBJECT_ID(N'dbo.INT_ODOO_CTA_MAP_AUDIT',N'U') IS NULL
  THROW 53503,'Falta el esquema de equivalencias previamente instalado.',1;

DECLARE @Entidades table(
  ID_ENTIDAD_FISCAL int NOT NULL PRIMARY KEY,
  ODOO_COMPANY_ID int NOT NULL UNIQUE,
  NOMBRE_LEGAL nvarchar(255) NOT NULL
);
INSERT @Entidades VALUES
