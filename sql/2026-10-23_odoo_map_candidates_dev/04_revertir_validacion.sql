/* Reverts only the 33 account-map approvals recorded from the confirmed authorization. */
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;

DECLARE @Aplicar bit=0,
        @ServidorEsperado sysname=N'dd7842d7ba7e',
        @BaseEsperada sysname=N'IOEDESARROLLO',
        @Cambio nvarchar(64)=N'IOE-ODOO-MAP-APPROVAL-20261023',
        @Actor nvarchar(255)=N'CODEX-ODOO-MAP-APPROVAL-20261023',
        @Aprobador nvarchar(255)=N'TITULAR IOE (autorizacion contable confirmada)',
        @Referencia nvarchar(250)=N'Autorizacion contable confirmada por titular en conversacion, 2026-10-23';
IF DB_NAME()<>@BaseEsperada OR @@SERVERNAME<>@ServidorEsperado
  THROW 53541,'Destino distinto de IOEDESARROLLO autorizado.',1;
IF @@TRANCOUNT<>0
  THROW 53542,'Ejecutar sin transaccion externa.',1;

DECLARE @Objetivos table(
  ID_ENTIDAD_FISCAL int NOT NULL,CTA_IOE nvarchar(255) NOT NULL,
  TIPO_EVENTO nvarchar(64) NOT NULL,SIGNO_IMPORTE varchar(12) NOT NULL
);
INSERT @Objetivos VALUES
 (1,N'101001001',N'ORD_TRABAJO_ABONO_CLIENTE','POSITIVO'),
 (1,N'101001001',N'ORD_TRABAJO_CARGO_CLIENTE','NEGATIVO'),
 (1,N'101001002',N'CREDITO_CLIENTE_ABONO','POSITIVO'),
 (1,N'101001002',N'CREDITO_CLIENTE_ABONO','NEGATIVO'),
 (1,N'101001002',N'CREDITO_CLIENTE_CARGO','NEGATIVO'),
 (1,N'101001003',N'CAJA_CHICA_DISPOSICION_REINTEGRO','POSITIVO'),
 (1,N'210001019',N'APARTADO_CLIENTE_ABONO','POSITIVO'),
 (1,N'210001019',N'APARTADO_CLIENTE_CARGO','NEGATIVO'),
 (1,N'704010003',N'OPV_SOBRANTE','NEGATIVO'),
 (1,N'704010003',N'OPV_FALTANTE','POSITIVO'),
 (1,N'704010004',N'GASTO_VARIOS_DISPOSICION','NEGATIVO');
INSERT @Objetivos
SELECT ID_ENTIDAD_FISCAL+1,CTA_IOE,TIPO_EVENTO,SIGNO_IMPORTE FROM @Objetivos WHERE ID_ENTIDAD_FISCAL=1;
INSERT @Objetivos
SELECT ID_ENTIDAD_FISCAL+1,CTA_IOE,TIPO_EVENTO,SIGNO_IMPORTE FROM @Objetivos WHERE ID_ENTIDAD_FISCAL=2;

IF (SELECT COUNT(*) FROM @Objetivos)<>33
  THROW 53543,'Lista de reversa incompleta.',1;
IF EXISTS(
  SELECT 1 FROM dbo.INT_ODOO_CTA_MAP m
  JOIN @Objetivos p ON m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL AND m.CTA_IOE=p.CTA_IOE
   AND m.TIPO_EVENTO=p.TIPO_EVENTO AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  WHERE m.ODOO_ENTORNO<>'ONLINE' OR m.SUC IS NOT NULL OR m.ROL_APUNTE<>'PRINCIPAL'
    OR m.ESTADO_MAPEO<>'VALIDADA' OR m.CREADO_POR<>N'CODEX-ODOO-MAP-20261023'
    OR m.APROBADO_POR<>@Aprobador OR m.REFERENCIA_APROBACION<>@Referencia
    OR (SELECT COUNT_BIG(*) FROM dbo.INT_ODOO_CTA_MAP_AUDIT a WHERE a.ID_MAPEO=m.ID_MAPEO)<>2
    OR NOT EXISTS(SELECT 1 FROM dbo.INT_ODOO_CTA_MAP_AUDIT a WHERE a.ID_MAPEO=m.ID_MAPEO
      AND a.ACCION='VALIDADA' AND a.ACTOR=@Actor AND JSON_VALUE(a.CAMPOS_JSON,'$.cambio')=@Cambio)
)
  THROW 53544,'Aprobación cambió o tiene auditoría posterior; no revertir automáticamente.',1;
IF (SELECT COUNT_BIG(*) FROM dbo.INT_ODOO_CTA_MAP m JOIN @Objetivos p
      ON m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL AND m.CTA_IOE=p.CTA_IOE
     AND m.TIPO_EVENTO=p.TIPO_EVENTO AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
     WHERE m.ESTADO_MAPEO='VALIDADA')<>33
  THROW 53545,'No se encontraron las 33 filas validadas.',1;

IF @Aplicar=0
BEGIN
  SELECT @@SERVERNAME servidor,DB_NAME() base,COUNT(*) filas_reversibles,
    N'Revierte VALIDADA a PENDIENTE y agrega auditoría; no borra historial' alcance
  FROM @Objetivos;
  RETURN;
END;

BEGIN TRY
  BEGIN TRAN;
  DECLARE @Revertidas table(ID_MAPEO bigint NOT NULL);
  UPDATE m WITH(UPDLOCK,HOLDLOCK)
    SET ESTADO_MAPEO='PENDIENTE',APROBADO_POR=NULL,REFERENCIA_APROBACION=NULL,
      FCN_APROBACION_UTC=NULL,MODIFICADO_POR=@Actor,FCN_MODIFICACION_UTC=SYSUTCDATETIME()
  OUTPUT inserted.ID_MAPEO INTO @Revertidas(ID_MAPEO)
  FROM dbo.INT_ODOO_CTA_MAP m JOIN @Objetivos p
    ON m.ID_ENTIDAD_FISCAL=p.ID_ENTIDAD_FISCAL AND m.CTA_IOE=p.CTA_IOE
   AND m.TIPO_EVENTO=p.TIPO_EVENTO AND m.SIGNO_IMPORTE=p.SIGNO_IMPORTE
  WHERE m.ODOO_ENTORNO='ONLINE' AND m.SUC IS NULL AND m.ROL_APUNTE='PRINCIPAL'
    AND m.ESTADO_MAPEO='VALIDADA' AND m.APROBADO_POR=@Aprobador
    AND m.REFERENCIA_APROBACION=@Referencia;
  IF (SELECT COUNT(*) FROM @Revertidas)<>33
    THROW 53546,'Reversa no afectó exactamente 33 filas.',1;
  INSERT dbo.INT_ODOO_CTA_MAP_AUDIT(ID_MAPEO,ACCION,CAMPOS_JSON,ACTOR)
  SELECT ID_MAPEO,'APROBACION_REVOCADA',
    (SELECT @Cambio AS cambio,@Referencia AS referencia,N'VALIDADA' AS estadoAnterior,
      N'PENDIENTE' AS estadoNuevo,N'Historial conservado' AS nota
     FOR JSON PATH,WITHOUT_ARRAY_WRAPPER),@Actor
  FROM @Revertidas;
  IF EXISTS(SELECT 1 FROM dbo.INT_ODOO_CTA_MAP WHERE ESTADO_MAPEO='VALIDADA') OR
     (SELECT COUNT_BIG(*) FROM dbo.INT_ODOO_CTA_MAP_AUDIT)<>99
    THROW 53547,'Postvalidación de reversa falló.',1;
  COMMIT;
  SELECT @@SERVERNAME servidor,DB_NAME() base,(SELECT COUNT(*) FROM @Revertidas) revertidas,
    (SELECT COUNT_BIG(*) FROM dbo.INT_ODOO_CTA_MAP_AUDIT) auditorias,
    N'Historial de aprobación conservado; mapas regresan a PENDIENTE' alcance;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;
  THROW;
END CATCH;
