/*
  DEV_PROVD - Devoluciones a proveedor.

  Reutiliza:
  - DAT_PROVD para proveedores;
  - DAT_ART para articulo, existencia, costo y jerarquias;
  - DAT_CMOV 102 para la salida administrativa;
  - DAT_CTR_DOC / DAT_MB51 para el movimiento oficial;
  - AUDIT_LOG para trazabilidad.

  La reserva no altera DAT_ART.STOCK. La salida se registra exclusivamente
  en sp_dev_provd_autorizar. El script es idempotente.
*/

