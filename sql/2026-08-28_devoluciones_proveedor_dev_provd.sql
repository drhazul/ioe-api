CREATE OR ALTER PROCEDURE dbo.sp_dev_provd_consolidar_envio
  @DOCUMENTOS NVARCHAR(MAX), @TRANSPORTISTA NVARCHAR(120), @GUIA NVARCHAR(120),
  @CAJAS INT, @RMA NVARCHAR(120)=NULL, @OBS NVARCHAR(1000)=NULL, @USR NVARCHAR(100)
AS
BEGIN
  SET NOCOUNT ON; SET XACT_ABORT ON;
  BEGIN TRY
    BEGIN TRANSACTION;
    IF ISJSON(@DOCUMENTOS)<>1 THROW 59260,'La lista de documentos no es valida.',1;
    DECLARE @DOCS TABLE(DOC NVARCHAR(40) PRIMARY KEY);
    INSERT @DOCS(DOC) SELECT DISTINCT LTRIM(RTRIM(CONVERT(NVARCHAR(40),[value]))) FROM OPENJSON(@DOCUMENTOS) WHERE NULLIF(LTRIM(RTRIM(CONVERT(NVARCHAR(40),[value]))),'') IS NOT NULL;
    IF NOT EXISTS(SELECT 1 FROM @DOCS) THROW 59261,'Debe seleccionar al menos una devolucion.',1;
    IF @CAJAS<=0 THROW 59262,'El numero de cajas debe ser mayor a cero.',1;
    IF NULLIF(LTRIM(RTRIM(ISNULL(@TRANSPORTISTA,''))),'') IS NULL OR NULLIF(LTRIM(RTRIM(ISNULL(@GUIA,''))),'') IS NULL THROW 59263,'Transportista y guia son requeridos.',1;
    IF EXISTS(SELECT 1 FROM @DOCS x LEFT JOIN dbo.DEV_DOC_PROVD h WITH(UPDLOCK,HOLDLOCK) ON h.DOC=x.DOC WHERE h.DOC IS NULL OR h.ESTATUS<>'AUTORIZADA') THROW 59264,'Todas las devoluciones deben estar AUTORIZADAS.',1;
    IF (SELECT COUNT(DISTINCT h.PROVD) FROM @DOCS x JOIN dbo.DEV_DOC_PROVD h ON h.DOC=x.DOC)<>1 THROW 59265,'Solo se consolidan devoluciones del mismo proveedor.',1;
    IF EXISTS(SELECT 1 FROM @DOCS x JOIN dbo.DEV_ENVIO_DOC ed ON ed.DOC=x.DOC) THROW 59266,'Una devolucion ya pertenece a otro envio.',1;
    DECLARE @PROVD INT=(SELECT TOP(1) h.PROVD FROM @DOCS x JOIN dbo.DEV_DOC_PROVD h ON h.DOC=x.DOC);
    INSERT dbo.DEV_ENVIO_PROVD(ENVIO,PROVD,TRANSPORTISTA,GUIA,CAJAS,RMA,OBS,USR_CREA)
    VALUES(NULL,@PROVD,@TRANSPORTISTA,@GUIA,@CAJAS,NULLIF(LTRIM(RTRIM(@RMA)),''),NULLIF(LTRIM(RTRIM(@OBS)),''),@USR);
    DECLARE @ID BIGINT=SCOPE_IDENTITY(),@ENVIO NVARCHAR(40);
    SET @ENVIO=CONCAT('ENV-DEV-',RIGHT(CONCAT('00000000',CONVERT(VARCHAR(20),@ID)),8));
    UPDATE dbo.DEV_ENVIO_PROVD SET ENVIO=@ENVIO WHERE ID=@ID;
    INSERT dbo.DEV_ENVIO_DOC(IDENVIO,DOC) SELECT @ID,DOC FROM @DOCS;
    UPDATE h SET ESTATUS='CONSOLIDADA',FCNM=SYSDATETIME() FROM dbo.DEV_DOC_PROVD h JOIN @DOCS x ON x.DOC=h.DOC;
    INSERT dbo.AUDIT_LOG(IDUSUARIO,ACTION,MODULO,ENTIDAD,ENTIDAD_ID,SUC,METADATA_JSON,FCNR)
    SELECT u.IDUSUARIO,'CONSOLIDAR_ENVIO','DEV_PROVD','DEV_ENVIO_PROVD',@ENVIO,NULL,CONCAT('{"documentos":',@DOCUMENTOS,'}'),SYSDATETIME() FROM dbo.USUARIO u WHERE UPPER(u.USERNAME)=UPPER(@USR);
    COMMIT;
    SELECT @ENVIO ENVIO;
  END TRY
  BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK;
    THROW;
  END CATCH
END;
GO

CREATE OR ALTER PROCEDURE dbo.sp_dev_provd_salida_fisica
  @ENVIO NVARCHAR(40), @USR NVARCHAR(100)
AS
BEGIN
  SET NOCOUNT ON; SET XACT_ABORT ON;
  BEGIN TRANSACTION;
  DECLARE @ID BIGINT,@ESTATUS NVARCHAR(30);
  SELECT @ID=ID,@ESTATUS=ESTATUS FROM dbo.DEV_ENVIO_PROVD WITH(UPDLOCK,HOLDLOCK) WHERE ENVIO=@ENVIO;
  IF @ID IS NULL BEGIN ROLLBACK; THROW 59270,'El envio no existe.',1; END;
  IF @ESTATUS='EN_TRANSITO' BEGIN COMMIT; SELECT @ENVIO ENVIO,'EN_TRANSITO' ESTATUS; RETURN; END;
  IF @ESTATUS<>'CONSOLIDADO' BEGIN ROLLBACK; THROW 59271,'El envio no se puede registrar como salida.',1; END;
