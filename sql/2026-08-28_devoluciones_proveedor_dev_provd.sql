    IF @ESTATUS IS NULL THROW 59277,'La devolucion no existe.',1;
    IF @ESTATUS='RECIBIDA' BEGIN COMMIT; SELECT @DOC DOC,'RECIBIDA' ESTATUS; RETURN; END;
