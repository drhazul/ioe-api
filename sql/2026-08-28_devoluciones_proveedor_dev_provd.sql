CREATE OR ALTER TRIGGER dbo.trg_dat_art_dev_provd_reserva
ON dbo.DAT_ART
AFTER UPDATE
AS
BEGIN
  SET NOCOUNT ON;
  IF NOT UPDATE(STOCK) RETURN;

  IF EXISTS(
    SELECT 1
    FROM inserted i
    CROSS APPLY(
      SELECT SUM(d.CTDA_BLOQ) RESERVADO
      FROM dbo.DEV_CTRL_PROVD d
      JOIN dbo.DEV_DOC_PROVD h ON h.DOC=d.DOC
      WHERE h.SUC=i.SUC AND h.ESTATUS='PENDIENTE'
        AND d.ART=i.ART AND d.ACTIVO=1 AND d.CTDA_BLOQ>0
    ) r
    WHERE ISNULL(i.STOCK,0)<ISNULL(r.RESERVADO,0)
  )
    THROW 59280,'La operacion intenta consumir inventario reservado para devolucion a proveedor.',1;
END;
GO

CREATE OR ALTER PROCEDURE dbo.sp_dev_provd_recalcular
  @DOC NVARCHAR(40)
AS
BEGIN
  SET NOCOUNT ON;
  UPDATE d SET IMPT=CONVERT(MONEY,CTDA_DEV*CTOP),FCNM=SYSDATETIME()
  FROM dbo.DEV_CTRL_PROVD d WHERE d.DOC=@DOC AND d.ACTIVO=1;
  UPDATE h SET FCNM=SYSDATETIME() FROM dbo.DEV_DOC_PROVD h WHERE h.DOC=@DOC;
END;
GO

CREATE OR ALTER PROCEDURE dbo.sp_dev_provd_crear
  @SUC NVARCHAR(20), @ALMACEN VARCHAR(10)='002', @PROVD INT,
  @TIPO_DEV INT, @DOC_OC NVARCHAR(255)=NULL, @DOC_REC NVARCHAR(255)=NULL,
  @OBS NVARCHAR(1000)=NULL, @USR NVARCHAR(100)
AS
BEGIN
  SET NOCOUNT ON; SET XACT_ABORT ON;
  BEGIN TRY
    BEGIN TRANSACTION;
    SET @SUC=UPPER(LTRIM(RTRIM(ISNULL(@SUC,''))));
    SET @ALMACEN=LTRIM(RTRIM(ISNULL(@ALMACEN,'002')));
    IF @SUC='' THROW 59200,'La sucursal es requerida.',1;
    IF NOT EXISTS(SELECT 1 FROM dbo.DAT_SUC WHERE UPPER(LTRIM(RTRIM(SUC)))=@SUC) THROW 59201,'La sucursal no existe.',1;
    IF NOT EXISTS(SELECT 1 FROM dbo.DAT_PROVD WHERE ID=@PROVD AND ISNULL(BLOQ,0)<>-1) THROW 59202,'El proveedor no existe o esta inactivo.',1;
    IF NOT EXISTS(SELECT 1 FROM dbo.DEV_TIPO_PROVD WHERE ID=@TIPO_DEV AND ACTIVO=1) THROW 59203,'El tipo de devolucion no es valido.',1;

    DECLARE @FOLIOS TABLE(ULTIMO BIGINT);
    MERGE dbo.DEV_FOLIO_PROVD WITH(HOLDLOCK) AS target
    USING(SELECT @SUC SUC) AS source ON target.SUC=source.SUC
    WHEN MATCHED THEN UPDATE SET ULTIMO=target.ULTIMO+1,FCNM=SYSDATETIME()
    WHEN NOT MATCHED THEN INSERT(SUC,ULTIMO) VALUES(source.SUC,1)
    OUTPUT inserted.ULTIMO INTO @FOLIOS;
    DECLARE @FOLIO BIGINT=(SELECT ULTIMO FROM @FOLIOS), @DOC NVARCHAR(40);
    SET @DOC=CONCAT('DEV-',@SUC,'-',RIGHT(CONCAT('00000000',CONVERT(VARCHAR(20),@FOLIO)),8));
    INSERT dbo.DEV_DOC_PROVD(DOC,SUC,ALMACEN,PROVD,DOC_OC,DOC_REC,TIPO_DEV,ESTATUS,OBS,USR_CREA)
    VALUES(@DOC,@SUC,@ALMACEN,@PROVD,NULLIF(LTRIM(RTRIM(@DOC_OC)),''),NULLIF(LTRIM(RTRIM(@DOC_REC)),''),@TIPO_DEV,'BORRADOR',NULLIF(LTRIM(RTRIM(@OBS)),''),@USR);
    INSERT dbo.AUDIT_LOG(IDUSUARIO,ACTION,MODULO,ENTIDAD,ENTIDAD_ID,SUC,METADATA_JSON,FCNR)
    SELECT IDUSUARIO,'CREAR','DEV_PROVD','DEV_DOC_PROVD',@DOC,@SUC,NULL,SYSDATETIME() FROM dbo.USUARIO WHERE UPPER(USERNAME)=UPPER(@USR);
    COMMIT;
    SELECT @DOC DOC;
  END TRY
  BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK;
    THROW;
  END CATCH
END;
GO

CREATE OR ALTER PROCEDURE dbo.sp_dev_provd_agregar_articulo
  @DOC NVARCHAR(40), @ART NVARCHAR(20), @CTDA_DEV DECIMAL(18,4),
  @CTOP MONEY=NULL, @MOV_DEV INT, @LOTE NVARCHAR(100)=NULL,
  @CADUCIDAD DATE=NULL, @OBS NVARCHAR(1000)=NULL, @USR NVARCHAR(100)
AS
BEGIN
  SET NOCOUNT ON; SET XACT_ABORT ON;
  BEGIN TRY
    BEGIN TRANSACTION;
    DECLARE @SUC NVARCHAR(20),@ESTATUS NVARCHAR(30),@COSTO MONEY;
    SELECT @SUC=SUC,@ESTATUS=ESTATUS FROM dbo.DEV_DOC_PROVD WITH(UPDLOCK,HOLDLOCK) WHERE DOC=@DOC;
    IF @ESTATUS IS NULL THROW 59210,'La devolucion no existe.',1;
    IF @ESTATUS<>'BORRADOR' THROW 59211,'Solo se editan articulos en BORRADOR.',1;
    IF @CTDA_DEV<=0 THROW 59212,'La cantidad debe ser mayor a cero.',1;
    SELECT @COSTO=COALESCE(NULLIF(@CTOP,0),CTOP,0) FROM dbo.DAT_ART WITH(UPDLOCK,HOLDLOCK) WHERE SUC=@SUC AND ART=@ART AND ISNULL(BLOQ,0)<>-1;
    IF @COSTO IS NULL THROW 59213,'El articulo no existe en la sucursal.',1;
    IF NOT EXISTS(SELECT 1 FROM dbo.DEV_MOTIVO_PROVD WHERE ID=@MOV_DEV AND ACTIVO=1) THROW 59214,'El motivo no es valido.',1;

    INSERT dbo.DEV_CTRL_PROVD(DOC,ART,CTDA_DEV,CTDA_BLOQ,CTOP,IMPT,LOTE,CADUCIDAD,MOV_DEV,OBS,USR_CREA)
    VALUES(@DOC,@ART,@CTDA_DEV,0,@COSTO,CONVERT(MONEY,@CTDA_DEV*@COSTO),NULLIF(LTRIM(RTRIM(@LOTE)),''),@CADUCIDAD,@MOV_DEV,NULLIF(LTRIM(RTRIM(@OBS)),''),@USR);
    DECLARE @IDPD BIGINT=SCOPE_IDENTITY();
    EXEC dbo.sp_dev_provd_recalcular @DOC=@DOC;
    COMMIT;
    SELECT @IDPD IDPD;
  END TRY
  BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK;
    THROW;
  END CATCH
END;
GO

CREATE OR ALTER PROCEDURE dbo.sp_dev_provd_solicitar
  @DOC NVARCHAR(40), @USR NVARCHAR(100)
AS
BEGIN
  SET NOCOUNT ON; SET XACT_ABORT ON;
  BEGIN TRY
    BEGIN TRANSACTION;
    DECLARE @SUC NVARCHAR(20),@ESTATUS NVARCHAR(30),@LOCK INT,@LOCK_RESOURCE NVARCHAR(255);
    SELECT @SUC=SUC,@ESTATUS=ESTATUS FROM dbo.DEV_DOC_PROVD WITH(UPDLOCK,HOLDLOCK) WHERE DOC=@DOC;
    IF @ESTATUS IS NULL THROW 59220,'La devolucion no existe.',1;
    IF @ESTATUS='PENDIENTE' BEGIN COMMIT; SELECT @DOC DOC,'PENDIENTE' ESTATUS; RETURN; END;
    IF @ESTATUS<>'BORRADOR' THROW 59221,'Solo se puede solicitar desde BORRADOR.',1;
    SET @LOCK_RESOURCE=CONCAT('DEV_PROVD_RESERVA_',@SUC);
    EXEC @LOCK=sys.sp_getapplock @Resource=@LOCK_RESOURCE,@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=15000;
    IF @LOCK<0 THROW 59222,'No fue posible bloquear el inventario para validar.',1;
    IF NOT EXISTS(SELECT 1 FROM dbo.DEV_CTRL_PROVD WHERE DOC=@DOC AND ACTIVO=1) THROW 59223,'La devolucion no tiene articulos.',1;
    IF NOT EXISTS(
      SELECT 1 FROM dbo.DEV_EVIDENCIA_PROVD e
      JOIN dbo.DEV_CTRL_PROVD d ON d.IDPD=e.IDPD
      WHERE d.DOC=@DOC AND d.ACTIVO=1
    ) THROW 59224,'La devolucion requiere una evidencia fotografica.',1;
    IF EXISTS(
      SELECT 1 FROM dbo.DEV_CTRL_PROVD d JOIN dbo.DEV_MOTIVO_PROVD m ON m.ID=d.MOV_DEV JOIN dbo.DEV_DOC_PROVD h ON h.DOC=d.DOC
      WHERE d.DOC=@DOC AND d.ACTIVO=1 AND m.REQUIERE_DOCUMENTO=1 AND NULLIF(LTRIM(RTRIM(COALESCE(h.DOC_REC,h.DOC_OC,''))),'') IS NULL
    ) THROW 59225,'El motivo requiere orden de compra o recepcion relacionada.',1;

    IF EXISTS(
      SELECT 1 FROM (SELECT ART,SUM(CTDA_DEV) CTD FROM dbo.DEV_CTRL_PROVD WHERE DOC=@DOC AND ACTIVO=1 GROUP BY ART) s
      LEFT JOIN dbo.DAT_ART a WITH(UPDLOCK,HOLDLOCK) ON a.SUC=@SUC AND a.ART=s.ART
      OUTER APPLY(SELECT SUM(x.CTDA_BLOQ) CTD FROM dbo.DEV_CTRL_PROVD x JOIN dbo.DEV_DOC_PROVD h ON h.DOC=x.DOC WHERE h.SUC=@SUC AND h.ESTATUS='PENDIENTE' AND x.ACTIVO=1 AND x.DOC<>@DOC AND x.ART=s.ART) r
      WHERE a.ART IS NULL OR ISNULL(a.STOCK,0)-ISNULL(r.CTD,0)<s.CTD
    ) THROW 59226,'Existencia disponible insuficiente para reservar.',1;

    UPDATE dbo.DEV_CTRL_PROVD SET CTDA_BLOQ=CTDA_DEV,FCNM=SYSDATETIME() WHERE DOC=@DOC AND ACTIVO=1;
    UPDATE dbo.DEV_DOC_PROVD SET ESTATUS='PENDIENTE',USR_SOLICITA=@USR,FCN_SOLICITA=SYSDATETIME(),FCNM=SYSDATETIME() WHERE DOC=@DOC;
    INSERT dbo.AUDIT_LOG(IDUSUARIO,ACTION,MODULO,ENTIDAD,ENTIDAD_ID,SUC,METADATA_JSON,FCNR)
    SELECT IDUSUARIO,'SOLICITAR_RESERVAR','DEV_PROVD','DEV_DOC_PROVD',@DOC,@SUC,NULL,SYSDATETIME() FROM dbo.USUARIO WHERE UPPER(USERNAME)=UPPER(@USR);
    COMMIT;
    SELECT @DOC DOC,'PENDIENTE' ESTATUS;
  END TRY
  BEGIN CATCH
    IF XACT_STATE()<>0 ROLLBACK;
    THROW;
  END CATCH
END;
GO

CREATE OR ALTER PROCEDURE dbo.sp_dev_provd_autorizar
  @DOC NVARCHAR(40), @USR NVARCHAR(100)
AS
BEGIN
  SET NOCOUNT ON; SET XACT_ABORT ON;
  BEGIN TRY
    BEGIN TRANSACTION;
    DECLARE @SUC NVARCHAR(20),@ALMACEN VARCHAR(10),@ESTATUS NVARCHAR(30),@LOCK INT,@LOCK_RESOURCE NVARCHAR(255);
    SELECT @SUC=SUC,@ALMACEN=ALMACEN,@ESTATUS=ESTATUS FROM dbo.DEV_DOC_PROVD WITH(UPDLOCK,HOLDLOCK) WHERE DOC=@DOC;
    IF @ESTATUS IS NULL THROW 59230,'La devolucion no existe.',1;
    IF @ESTATUS IN ('AUTORIZADA','CONSOLIDADA','EN_TRANSITO') BEGIN COMMIT; SELECT @DOC DOC,@ESTATUS ESTATUS; RETURN; END;
    IF @ESTATUS<>'PENDIENTE' THROW 59231,'Solo se autoriza una devolucion PENDIENTE.',1;
    SET @LOCK_RESOURCE=CONCAT('DEV_PROVD_RESERVA_',@SUC);
    EXEC @LOCK=sys.sp_getapplock @Resource=@LOCK_RESOURCE,@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=15000;
    IF @LOCK<0 THROW 59232,'No fue posible bloquear el inventario para autorizar.',1;
    IF NOT EXISTS(SELECT 1 FROM dbo.DAT_CMOV WHERE CMOV=102) THROW 59233,'DAT_CMOV no tiene configurado el movimiento 102.',1;
    IF EXISTS(
      SELECT 1 FROM (SELECT ART,SUM(CTDA_BLOQ) CTD FROM dbo.DEV_CTRL_PROVD WHERE DOC=@DOC AND ACTIVO=1 GROUP BY ART) q
      LEFT JOIN dbo.DAT_ART a WITH(UPDLOCK,HOLDLOCK) ON a.SUC=@SUC AND a.ART=q.ART
      WHERE a.ART IS NULL OR q.CTD<=0 OR ISNULL(a.STOCK,0)<q.CTD
    ) THROW 59234,'La existencia cambio y ya no permite autorizar la devolucion.',1;

    IF NOT EXISTS(SELECT 1 FROM dbo.DAT_CTR_DOC WITH(UPDLOCK,HOLDLOCK) WHERE DOC=@DOC)
      INSERT dbo.DAT_CTR_DOC(DOC,CLSMOV,FCND,[USER],STAT) VALUES(@DOC,'102',SYSDATETIME(),@USR,'V');

    INSERT dbo.DAT_MB51(IDPD,[USER],CLSM,DOCP,ART,CTDA,CTOT,FCND,FCNC,TXT,ALMACEN,VTAESP,SUC)
    SELECT CONCAT('DEV-',d.DOC,'-',d.IDPD),@USR,102,d.DOC,d.ART,-ABS(CONVERT(FLOAT,d.CTDA_BLOQ)),-ABS(CONVERT(FLOAT,d.CTDA_BLOQ))*CONVERT(FLOAT,d.CTOP),SYSDATETIME(),SYSDATETIME(),CONCAT('DEVOLUCION A PROVEEDOR ',d.DOC),@ALMACEN,0,@SUC
    FROM dbo.DEV_CTRL_PROVD d WHERE d.DOC=@DOC AND d.ACTIVO=1 AND d.CTDA_BLOQ>0
      AND NOT EXISTS(SELECT 1 FROM dbo.DAT_MB51 m WHERE m.IDPD=CONCAT('DEV-',d.DOC,'-',d.IDPD));

    DECLARE @SALIDA TABLE(ART NVARCHAR(20) PRIMARY KEY,CTD DECIMAL(18,4));
    INSERT @SALIDA(ART,CTD) SELECT ART,SUM(CTDA_BLOQ) FROM dbo.DEV_CTRL_PROVD WHERE DOC=@DOC AND ACTIVO=1 GROUP BY ART;
    UPDATE dbo.DEV_CTRL_PROVD SET CTDA_BLOQ=0,FCNM=SYSDATETIME() WHERE DOC=@DOC AND ACTIVO=1;
    UPDATE a SET STOCK=ISNULL(a.STOCK,0)-q.CTD FROM dbo.DAT_ART a JOIN @SALIDA q ON q.ART=a.ART WHERE a.SUC=@SUC;
    UPDATE dbo.DEV_DOC_PROVD SET ESTATUS='AUTORIZADA',USR_AUTORIZA=@USR,FCN_AUTORIZA=SYSDATETIME(),DOC_MB51=@DOC,FCNM=SYSDATETIME() WHERE DOC=@DOC;
    INSERT dbo.AUDIT_LOG(IDUSUARIO,ACTION,MODULO,ENTIDAD,ENTIDAD_ID,SUC,METADATA_JSON,FCNR)
    SELECT IDUSUARIO,'AUTORIZAR_CONTABILIZAR','DEV_PROVD','DEV_DOC_PROVD',@DOC,@SUC,'{"movimiento":102}',SYSDATETIME() FROM dbo.USUARIO WHERE UPPER(USERNAME)=UPPER(@USR);
    COMMIT;
    SELECT @DOC DOC,'AUTORIZADA' ESTATUS;
  END TRY
  BEGIN CATCH
