  AND COL_LENGTH('dbo.DAT_CMOV', 'CMOV') IS NOT NULL
  AND COL_LENGTH('dbo.DAT_CMOV', 'TXTM') IS NOT NULL
  AND COL_LENGTH('dbo.DAT_CMOV', 'MODULO') IS NOT NULL
  AND COL_LENGTH('dbo.DAT_CMOV', 'RELACION') IS NOT NULL
  AND COL_LENGTH('dbo.DAT_CMOV', 'TIPO') IS NOT NULL
  AND COL_LENGTH('dbo.DAT_CMOV', 'NDOC') IS NOT NULL
  AND COL_LENGTH('dbo.DAT_CMOV', 'BLOQ') IS NOT NULL
