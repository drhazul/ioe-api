  UPDATE dbo.DAT_CMOV
  SET
    TXTM = 'VENTA TICKET RELACIONADO',
    MODULO = 'PUNTOV',
    RELACION = '',
    TIPO = 'CARGO',
    NDOC = NULL,
    BLOQ = 'VTAYDEV'
  WHERE CMOV = 206;

  IF @@ROWCOUNT = 0
  BEGIN
