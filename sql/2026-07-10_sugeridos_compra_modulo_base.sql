USING (VALUES
  (N'ABIERTO', 10),
  (N'PENDIENTE', 20),
  (N'PROCESADO', 30),
  (N'PARCIAL', 40),
  (N'RECIBIDO', 50),
  (N'CERRADO', 60),
  (N'ANULADO', 90)
) AS source([DESC], ORDEN)
ON target.[DESC] = source.[DESC]
WHEN MATCHED THEN
  UPDATE SET ACTIVO = 1, ORDEN = source.ORDEN
WHEN NOT MATCHED THEN
  INSERT ([DESC], ACTIVO, ORDEN) VALUES (source.[DESC], 1, source.ORDEN);
