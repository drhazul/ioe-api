-- Target: 192.168.10.234:1433 / IOELOCAL.
-- Rename only; preserve IDMOD_FRONT and all group assignments.
-- Rollback: same guards, exchange FACTURA_QUADRUM and FACTURA_PRUEBAS.
SET XACT_ABORT ON;
BEGIN TRY
  BEGIN TRANSACTION;
  IF DB_NAME() <> N'IOELOCAL'
    THROW 51000, 'Wrong database; expected IOELOCAL.', 1;
  IF EXISTS (SELECT 1 FROM dbo.MOD_FRONT WITH (UPDLOCK, HOLDLOCK)
             WHERE CODIGO = N'FACTURA_QUADRUM' AND IDMOD_FRONT <> 20008)
    THROW 51001, 'FACTURA_QUADRUM already belongs to another module.', 1;
  IF NOT EXISTS (SELECT 1 FROM dbo.MOD_FRONT WITH (UPDLOCK, HOLDLOCK)
                 WHERE IDMOD_FRONT = 20008
                   AND CODIGO IN (N'FACTURA_PRUEBAS', N'FACTURA_QUADRUM')
                   AND NOMBRE = N'FACTURACION QUADRUM')
    THROW 51002, 'Module identity differs from preflight.', 1;
  UPDATE dbo.MOD_FRONT SET CODIGO = N'FACTURA_QUADRUM'
    WHERE IDMOD_FRONT = 20008 AND CODIGO = N'FACTURA_PRUEBAS';
  SELECT IDMOD_FRONT, CODIGO, NOMBRE, ACTIVO, DEPTO
    FROM dbo.MOD_FRONT WHERE IDMOD_FRONT = 20008;
  COMMIT TRANSACTION;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
  THROW;
END CATCH;
