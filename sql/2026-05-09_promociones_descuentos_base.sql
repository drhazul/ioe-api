  IF COL_LENGTH('dbo.PROMO_CAB', 'IMP_DESC') IS NULL
    ALTER TABLE dbo.PROMO_CAB ADD IMP_DESC MONEY NULL;

  IF COL_LENGTH('dbo.PROMO_CAB', 'PRIORIDAD') IS NULL
    ALTER TABLE dbo.PROMO_CAB ADD PRIORIDAD INT NOT NULL CONSTRAINT DF_PROMO_CAB_PRIORIDAD DEFAULT (100);

  IF COL_LENGTH('dbo.PROMO_CAB', 'COMBINABLE') IS NULL
    ALTER TABLE dbo.PROMO_CAB ADD COMBINABLE INT NOT NULL CONSTRAINT DF_PROMO_CAB_COMBINABLE DEFAULT (0);

  IF COL_LENGTH('dbo.PROMO_CAB', 'MAX_APLI_FOLIO') IS NULL
    ALTER TABLE dbo.PROMO_CAB ADD MAX_APLI_FOLIO INT NULL;

  IF COL_LENGTH('dbo.PROMO_CAB', 'CREADO_POR') IS NULL
    ALTER TABLE dbo.PROMO_CAB ADD CREADO_POR INT NULL;

  IF COL_LENGTH('dbo.PROMO_CAB', 'FCNR') IS NULL
    ALTER TABLE dbo.PROMO_CAB ADD FCNR DATETIME NOT NULL CONSTRAINT DF_PROMO_CAB_FCNR DEFAULT (GETDATE());

  IF COL_LENGTH('dbo.PROMO_CAB', 'MOD_POR') IS NULL
    ALTER TABLE dbo.PROMO_CAB ADD MOD_POR INT NULL;

  IF COL_LENGTH('dbo.PROMO_CAB', 'FCMOD') IS NULL
    ALTER TABLE dbo.PROMO_CAB ADD FCMOD DATETIME NULL;

  IF OBJECT_ID('dbo.PROMO_REGLA_CRITERIO', 'U') IS NULL
  BEGIN
    CREATE TABLE dbo.PROMO_REGLA_CRITERIO (
      ID_CRITERIO BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_PROMO_REGLA_CRITERIO PRIMARY KEY,
      ID_PROM INT NOT NULL,
      SUC NVARCHAR(10) NULL,
      CLIENTE FLOAT NULL,
      DEPA FLOAT NULL,
      SUBD FLOAT NULL,
      CLAS FLOAT NULL,
      SCLA FLOAT NULL,
      SCLA2 FLOAT NULL,
      GUIA NVARCHAR(50) NULL,
      ART NVARCHAR(50) NULL,
      UPC NVARCHAR(50) NULL,
      EST INT NOT NULL CONSTRAINT DF_PROMO_REGLA_CRITERIO_EST DEFAULT (1),
      FCNR DATETIME NOT NULL CONSTRAINT DF_PROMO_REGLA_CRITERIO_FCNR DEFAULT (GETDATE())
    );

    ALTER TABLE dbo.PROMO_REGLA_CRITERIO
      ADD CONSTRAINT FK_PROMO_REGLA_CRITERIO_PROMO_CAB
      FOREIGN KEY (ID_PROM) REFERENCES dbo.PROMO_CAB(ID_PROM);
  END;

  IF OBJECT_ID('dbo.PROMO_REGLA_BENEFICIO', 'U') IS NULL
  BEGIN
    CREATE TABLE dbo.PROMO_REGLA_BENEFICIO (
      ID_BENEFICIO BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_PROMO_REGLA_BENEFICIO PRIMARY KEY,
      ID_PROM INT NOT NULL,
      T_BENEFICIO NVARCHAR(30) NOT NULL,
