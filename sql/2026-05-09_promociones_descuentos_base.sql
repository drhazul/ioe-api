      ADD CONSTRAINT FK_PROMO_TICKET_DESC_APLI_PV_TICKET_LOG
      FOREIGN KEY (ID) REFERENCES dbo.PV_TICKET_LOG(ID);

    CREATE UNIQUE INDEX UX_PROMO_TICKET_DESC_APLI_ID_IDDESC
