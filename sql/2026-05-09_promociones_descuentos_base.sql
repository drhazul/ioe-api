      PRIORIDAD INT NOT NULL CONSTRAINT DF_PROMO_REGLA_BENEFICIO_PRIORIDAD DEFAULT (100),
      ACUMULABLE INT NOT NULL CONSTRAINT DF_PROMO_REGLA_BENEFICIO_ACUM DEFAULT (0),
      EST INT NOT NULL CONSTRAINT DF_PROMO_REGLA_BENEFICIO_EST DEFAULT (1),
      FCNR DATETIME NOT NULL CONSTRAINT DF_PROMO_REGLA_BENEFICIO_FCNR DEFAULT (GETDATE())
    );

