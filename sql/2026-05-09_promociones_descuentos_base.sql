  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_PROMO_REGLA_CRITERIO_IDPROM' AND object_id = OBJECT_ID('dbo.PROMO_REGLA_CRITERIO'))
    CREATE INDEX IX_PROMO_REGLA_CRITERIO_IDPROM ON dbo.PROMO_REGLA_CRITERIO(ID_PROM, EST);

  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_PROMO_REGLA_BENEFICIO_IDPROM' AND object_id = OBJECT_ID('dbo.PROMO_REGLA_BENEFICIO'))
    CREATE INDEX IX_PROMO_REGLA_BENEFICIO_IDPROM ON dbo.PROMO_REGLA_BENEFICIO(ID_PROM, EST, PRIORIDAD);

  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_PROMO_TICKET_DESC_APLI_IDFOL' AND object_id = OBJECT_ID('dbo.PROMO_TICKET_DESC_APLI'))
    CREATE INDEX IX_PROMO_TICKET_DESC_APLI_IDFOL ON dbo.PROMO_TICKET_DESC_APLI(IDFOL, FCNDES);

  IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = 'IX_PROMO_TICKET_GRATIS_REL_IDFOL' AND object_id = OBJECT_ID('dbo.PROMO_TICKET_GRATIS_REL'))
    CREATE INDEX IX_PROMO_TICKET_GRATIS_REL_IDFOL ON dbo.PROMO_TICKET_GRATIS_REL(IDFOL_ORIG, FCNR);

  COMMIT;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT > 0 ROLLBACK;
  THROW;
END CATCH;
GO

CREATE OR ALTER PROCEDURE dbo.sp_promo_desc_aplicadas_folio
  @IDFOL NVARCHAR(255)
AS
BEGIN
  SET NOCOUNT ON;

  SELECT
    a.ID_APLI,
    a.ID,
    a.IDFOL,
    a.UPC,
    a.ART,
    a.IDDESC,
    c.DESC_PROMO,
    c.T_PROM,
    a.IMPTDESC,
    a.PVTAT_ORIG,
    a.PVTAT_FIN,
    a.FCNDES,
    a.IDUSUARIO
  FROM dbo.PROMO_TICKET_DESC_APLI a
  INNER JOIN dbo.PROMO_CAB c
    ON c.ID_PROM = a.IDDESC
  WHERE a.IDFOL = @IDFOL
  ORDER BY a.FCNDES DESC, a.ID_APLI DESC;
END;
GO

CREATE OR ALTER PROCEDURE dbo.sp_promo_evaluar_folio
  @IDFOL NVARCHAR(255)
AS
BEGIN
  SET NOCOUNT ON;

  DECLARE @SUC NVARCHAR(255) = '';
  DECLARE @CLIENTE FLOAT = NULL;

  SELECT TOP 1
    @SUC = LTRIM(RTRIM(ISNULL(f.SUC, ''))),
    @CLIENTE = TRY_CONVERT(FLOAT, f.CLIEN)
  FROM dbo.PV_CTR_FOL_ASVR f
  WHERE f.IDFOL = @IDFOL OR f.IDFOLINICIAL = @IDFOL
  ORDER BY CASE WHEN f.IDFOL = @IDFOL THEN 0 ELSE 1 END, ISNULL(f.FCNM, f.FCN) DESC;

  IF @SUC = ''
  BEGIN
    SELECT CAST(0 AS INT) AS total_registros WHERE 1 = 0;
    RETURN;
  END;

  ;WITH base AS (
    SELECT
      t.ID,
      t.IDFOL,
      t.ART,
      t.UPC,
      ISNULL(TRY_CONVERT(MONEY, t.PVTAT), ISNULL(TRY_CONVERT(FLOAT, t.CTD), 0) * ISNULL(TRY_CONVERT(MONEY, t.PVTA), 0)) AS PVTAT,
      a.DEPA,
      a.SUBD,
      a.CLAS,
      a.SCLA,
      a.SCLA2,
      jr.GUIA
    FROM dbo.PV_TICKET_LOG t
    LEFT JOIN dbo.DAT_ART a
      ON a.SUC = @SUC
     AND LTRIM(RTRIM(ISNULL(a.ART, ''))) = LTRIM(RTRIM(ISNULL(t.ART, '')))
    OUTER APPLY (
      SELECT TOP 1 j.GUIA
      FROM dbo.DAT_DET_JRQ_SVR j
      WHERE LTRIM(RTRIM(ISNULL(j.ART, ''))) = LTRIM(RTRIM(ISNULL(t.ART, '')))
        AND (LTRIM(RTRIM(ISNULL(j.SUC, ''))) = @SUC OR ISNULL(j.SUC, '') = '')
      ORDER BY CASE WHEN LTRIM(RTRIM(ISNULL(j.SUC, ''))) = @SUC THEN 0 ELSE 1 END
    ) jr
    WHERE t.IDFOL = @IDFOL
  )
  SELECT
    b.ID,
    b.IDFOL,
    b.ART,
    b.UPC,
    b.PVTAT,
    c.ID_PROM,
    c.DESC_PROMO,
    c.T_PROM,
    rb.ID_BENEFICIO,
    rb.T_BENEFICIO,
    rb.PRC_DESC,
    rb.IMP_DESC,
    rb.ART_GRATIS,
    rb.UPC_GRATIS,
    rb.CANT_GRATIS,
    rb.PRECIO_GRATIS,
    rb.PRIORIDAD,
    rb.ACUMULABLE
  FROM base b
  INNER JOIN dbo.PROMO_CAB c
    ON (c.EST IN (1, -1) OR c.EST IS NULL)
   AND (c.FCN_INI IS NULL OR CONVERT(DATE, c.FCN_INI) <= CONVERT(DATE, GETDATE()))
   AND (c.FCN_TER IS NULL OR CONVERT(DATE, c.FCN_TER) >= CONVERT(DATE, GETDATE()))
   AND (
        LTRIM(RTRIM(ISNULL(c.SUC, ''))) = ''
        OR LTRIM(RTRIM(ISNULL(c.SUC, ''))) = '*'
        OR CHARINDEX(
             ',' + UPPER(@SUC) + ',',
             ',' + REPLACE(REPLACE(UPPER(LTRIM(RTRIM(ISNULL(c.SUC, '')))), ' ', ''), ';', ',') + ','
           ) > 0
       )
  INNER JOIN dbo.PROMO_REGLA_BENEFICIO rb
    ON rb.ID_PROM = c.ID_PROM
   AND rb.EST = 1
  WHERE EXISTS (
    SELECT 1
    FROM dbo.PROMO_REGLA_CRITERIO rc
    WHERE rc.ID_PROM = c.ID_PROM
      AND rc.EST = 1
      AND (
           LTRIM(RTRIM(ISNULL(rc.SUC, ''))) = ''
           OR LTRIM(RTRIM(ISNULL(rc.SUC, ''))) = '*'
           OR CHARINDEX(
                ',' + UPPER(@SUC) + ',',
                ',' + REPLACE(REPLACE(UPPER(LTRIM(RTRIM(ISNULL(rc.SUC, '')))), ' ', ''), ';', ',') + ','
              ) > 0
          )
      AND (rc.CLIENTE IS NULL OR rc.CLIENTE = @CLIENTE)
      AND (rc.DEPA IS NULL OR rc.DEPA = b.DEPA)
      AND (rc.SUBD IS NULL OR rc.SUBD = b.SUBD)
      AND (rc.CLAS IS NULL OR rc.CLAS = b.CLAS)
      AND (rc.SCLA IS NULL OR rc.SCLA = b.SCLA)
      AND (rc.SCLA2 IS NULL OR rc.SCLA2 = b.SCLA2)
      AND (LTRIM(RTRIM(ISNULL(rc.GUIA, ''))) = '' OR LTRIM(RTRIM(ISNULL(rc.GUIA, ''))) = LTRIM(RTRIM(ISNULL(b.GUIA, ''))))
      AND (LTRIM(RTRIM(ISNULL(rc.ART, ''))) = '' OR LTRIM(RTRIM(ISNULL(rc.ART, ''))) = LTRIM(RTRIM(ISNULL(b.ART, ''))))
      AND (LTRIM(RTRIM(ISNULL(rc.UPC, ''))) = '' OR LTRIM(RTRIM(ISNULL(rc.UPC, ''))) = LTRIM(RTRIM(ISNULL(b.UPC, ''))))
  )
  ORDER BY rb.PRIORIDAD ASC, c.PRIORIDAD ASC, c.ID_PROM ASC;
END;
