      ID_APLI BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_PROMO_TICKET_DESC_APLI PRIMARY KEY,
      ID NVARCHAR(255) NOT NULL,
      IDFOL NVARCHAR(255) NOT NULL,
      UPC NVARCHAR(255) NULL,
      ART NVARCHAR(255) NULL,
      IDDESC INT NOT NULL,
      IMPTDESC MONEY NOT NULL,
      FCNDES DATETIME NOT NULL CONSTRAINT DF_PROMO_TICKET_DESC_APLI_FCNDES DEFAULT (GETDATE()),
      PVTAT_ORIG MONEY NULL,
