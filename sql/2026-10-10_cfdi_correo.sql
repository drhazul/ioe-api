  Este archivo solo prepara DDL. No ejecutar sin preflight de solo lectura,
  respaldo/reversa y autorización explícita para la base destino exacta.
*/
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF OBJECT_ID(N'dbo.FACT_CFDI_EMAIL_CONFIG', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.FACT_CFDI_EMAIL_CONFIG (
    ID TINYINT NOT NULL
      CONSTRAINT PK_FACT_CFDI_EMAIL_CONFIG PRIMARY KEY
      CONSTRAINT CK_FACT_CFDI_EMAIL_CONFIG_ID CHECK (ID = 1),
    AUTOMATICO BIT NOT NULL
      CONSTRAINT DF_FACT_CFDI_EMAIL_CONFIG_AUTOMATICO DEFAULT (0),
    NOMBRE_REMITENTE NVARCHAR(100) NOT NULL
      CONSTRAINT DF_FACT_CFDI_EMAIL_CONFIG_NOMBRE DEFAULT (N'Facturación IOE'),
    CUENTA_GOOGLE NVARCHAR(254) NULL,
    REFRESH_TOKEN_CIFRADO NVARCHAR(MAX) NULL,
    AUTO_ENABLED_AT DATETIME2(0) NULL,
    ULTIMA_CONEXION DATETIME2(0) NULL,
    CREADO_EN DATETIME2(0) NOT NULL
      CONSTRAINT DF_FACT_CFDI_EMAIL_CONFIG_CREADO DEFAULT (SYSDATETIME()),
    ACTUALIZADO_EN DATETIME2(0) NOT NULL
      CONSTRAINT DF_FACT_CFDI_EMAIL_CONFIG_ACTUALIZADO DEFAULT (SYSDATETIME())
  );
END;

IF NOT EXISTS (
  SELECT 1 FROM dbo.FACT_CFDI_EMAIL_CONFIG WHERE ID = 1
)
BEGIN
  INSERT INTO dbo.FACT_CFDI_EMAIL_CONFIG
    (ID, AUTOMATICO, NOMBRE_REMITENTE)
  VALUES
    (1, 0, N'Facturación IOE');
END;

IF OBJECT_ID(N'dbo.FACT_CFDI_EMAIL_OUTBOX', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.FACT_CFDI_EMAIL_OUTBOX (
    ID BIGINT IDENTITY(1,1) NOT NULL
      CONSTRAINT PK_FACT_CFDI_EMAIL_OUTBOX PRIMARY KEY,
    IDFOL NVARCHAR(100) NOT NULL,
    CFDI_UUID NVARCHAR(36) NOT NULL,
    DESTINATARIO_CIFRADO NVARCHAR(MAX) NULL,
    ESTADO VARCHAR(32) NOT NULL,
    INTENTOS INT NOT NULL
      CONSTRAINT DF_FACT_CFDI_EMAIL_OUTBOX_INTENTOS DEFAULT (0),
    SIGUIENTE_INTENTO_EN DATETIME2(0) NULL,
    ULTIMO_CODIGO VARCHAR(80) NULL,
    ULTIMO_MENSAJE NVARCHAR(500) NULL,
    GMAIL_MESSAGE_ID NVARCHAR(200) NULL,
    CREADO_EN DATETIME2(0) NOT NULL
      CONSTRAINT DF_FACT_CFDI_EMAIL_OUTBOX_CREADO DEFAULT (SYSDATETIME()),
    ACTUALIZADO_EN DATETIME2(0) NOT NULL
      CONSTRAINT DF_FACT_CFDI_EMAIL_OUTBOX_ACTUALIZADO DEFAULT (SYSDATETIME()),
    ENVIADO_EN DATETIME2(0) NULL,
    CONSTRAINT CK_FACT_CFDI_EMAIL_OUTBOX_ESTADO CHECK (
      ESTADO IN (
        'PENDIENTE',
        'PROCESANDO',
        'ENVIADO',
        'REINTENTABLE',
        'ERROR_FINAL',
        'OMITIDO_SIN_DESTINATARIO',
        'OMITIDO_DESHABILITADO',
        'INCIERTO'
      )
    )
  );
END;

IF NOT EXISTS (
  SELECT 1 FROM sys.indexes
  WHERE object_id = OBJECT_ID(N'dbo.FACT_CFDI_EMAIL_OUTBOX')
    AND name = N'UX_FACT_CFDI_EMAIL_OUTBOX_UUID'
)
BEGIN
  CREATE UNIQUE INDEX UX_FACT_CFDI_EMAIL_OUTBOX_UUID
    ON dbo.FACT_CFDI_EMAIL_OUTBOX (CFDI_UUID);
END;

IF NOT EXISTS (
  SELECT 1 FROM sys.indexes
  WHERE object_id = OBJECT_ID(N'dbo.FACT_CFDI_EMAIL_OUTBOX')
    AND name = N'IX_FACT_CFDI_EMAIL_OUTBOX_PENDIENTE'
)
BEGIN
  CREATE INDEX IX_FACT_CFDI_EMAIL_OUTBOX_PENDIENTE
    ON dbo.FACT_CFDI_EMAIL_OUTBOX
      (ESTADO, SIGUIENTE_INTENTO_EN, CREADO_EN, ID);
END;

IF OBJECT_ID(N'dbo.FACT_CFDI_EMAIL_OAUTH_STATE', N'U') IS NULL
BEGIN
  CREATE TABLE dbo.FACT_CFDI_EMAIL_OAUTH_STATE (
    ID BIGINT IDENTITY(1,1) NOT NULL
      CONSTRAINT PK_FACT_CFDI_EMAIL_OAUTH_STATE PRIMARY KEY,
    HASH CHAR(64) NOT NULL,
    EXPIRA_EN DATETIME2(0) NOT NULL,
    CONSUMIDO_EN DATETIME2(0) NULL,
    CREADO_EN DATETIME2(0) NOT NULL
      CONSTRAINT DF_FACT_CFDI_EMAIL_OAUTH_STATE_CREADO DEFAULT (SYSDATETIME())
  );
END;

IF NOT EXISTS (
  SELECT 1 FROM sys.indexes
  WHERE object_id = OBJECT_ID(N'dbo.FACT_CFDI_EMAIL_OAUTH_STATE')
    AND name = N'UX_FACT_CFDI_EMAIL_OAUTH_STATE_HASH'
)
BEGIN
  CREATE UNIQUE INDEX UX_FACT_CFDI_EMAIL_OAUTH_STATE_HASH
    ON dbo.FACT_CFDI_EMAIL_OAUTH_STATE (HASH);
END;

COMMIT TRANSACTION;
