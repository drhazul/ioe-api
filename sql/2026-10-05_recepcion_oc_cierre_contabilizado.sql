/*
  DAT_REC: cierre definitivo de la O.C. al contabilizar.
  - La recepción y la cabecera de la O.C. quedan CONTABILIZADO.
  - Los faltantes permanecen en REC_DET_PED/REC_CTO_HIST como evidencia.
  - Regulariza todas las cabeceras PARCIAL que ya tienen una recepción
    CONTABILIZADO, sin modificar cantidades ni movimientos de inventario.
*/
SET ANSI_NULLS ON;
SET QUOTED_IDENTIFIER ON;
