/*
  IOELOCAL: permitir que ANALISTA_ORD vea ORDs internas en flujo 9.
  Esto incluye las incidencias de merma/cambio que pasan de flujo 8 a 9.
*/
IF DB_NAME() <> N'IOELOCAL'
  THROW 59142, 'Este ajuste solo se permite en IOELOCAL', 1;
GO

SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRY
  BEGIN TRANSACTION;

  IF NOT EXISTS (
    SELECT 1
    FROM dbo.DAT_JAO_ORD_FLUJO_VIS
    WHERE UPPER(LTRIM(RTRIM(MODULO))) = N'DAT_JAO_ORD'
      AND UPPER(LTRIM(RTRIM(PANEL_MODE))) = N'OPERATIVO'
      AND UPPER(LTRIM(RTRIM(ROLE_CODE))) = N'ANALISTA_ORD'
      AND TRY_CONVERT(FLOAT, ESTA) = 9
  )
    THROW 59143, 'No existe la regla ANALISTA_ORD para el flujo 9', 1;

  UPDATE dbo.DAT_JAO_ORD_FLUJO_VIS
  SET SOLO_EXTERNO = 0
  WHERE UPPER(LTRIM(RTRIM(MODULO))) = N'DAT_JAO_ORD'
    AND UPPER(LTRIM(RTRIM(PANEL_MODE))) = N'OPERATIVO'
    AND UPPER(LTRIM(RTRIM(ROLE_CODE))) = N'ANALISTA_ORD'
    AND TRY_CONVERT(FLOAT, ESTA) = 9
    AND SOLO_EXTERNO = 1;

  COMMIT TRANSACTION;
END TRY
BEGIN CATCH
  IF XACT_STATE() <> 0 ROLLBACK TRANSACTION;
  THROW;
END CATCH;
GO

SELECT MODULO, PANEL_MODE, ROLE_CODE, ESTA, SOLO_EXTERNO, ORDEN
FROM dbo.DAT_JAO_ORD_FLUJO_VIS
WHERE UPPER(LTRIM(RTRIM(MODULO))) = N'DAT_JAO_ORD'
  AND UPPER(LTRIM(RTRIM(PANEL_MODE))) = N'OPERATIVO'
  AND UPPER(LTRIM(RTRIM(ROLE_CODE))) = N'ANALISTA_ORD'
  AND TRY_CONVERT(FLOAT, ESTA) = 9;
GO
