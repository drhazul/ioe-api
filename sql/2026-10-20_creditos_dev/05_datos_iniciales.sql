/* Titular autorizo 2026-10-20 los 11 DAT_SUC, incluido 000, para IOE BUSINESS. */
IF DB_NAME()<>N'IOEDESARROLLO' OR @@SERVERNAME<>N'dd7842d7ba7e' THROW 53301,'Destino no autorizado.',1;
SET NOCOUNT ON; SET XACT_ABORT ON;
DECLARE @lock int,@correlation uniqueidentifier=NEWID();
DECLARE @whitelist table(SUC nvarchar(10) PRIMARY KEY);
INSERT @whitelist VALUES('000'),('DF01'),('DF02'),('DF03'),('DF04'),('DF05'),('DF06'),('DF10'),('DF14'),('DF16'),('OM01');
DECLARE @cambios table(SUC nvarchar(10),ANTES int,DESPUES int);
BEGIN TRY
  BEGIN TRAN;
  EXEC @lock=sys.sp_getapplock @Resource=N'PS_CREDITOS_CONFIG_V1',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=5000;
  IF @lock<0 THROW 53402,'Configuracion ocupada.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.EMPRESA WHERE idempresa=1 AND razon_social=N'IOE BUSINESS')
    THROW 53302,'Empresa autorizada no coincide.',1;
  IF (SELECT COUNT(*) FROM dbo.DAT_SUC)<>11 OR EXISTS(SELECT SUC FROM dbo.DAT_SUC EXCEPT SELECT SUC FROM @whitelist)
    OR EXISTS(SELECT 1 FROM dbo.DAT_SUC WHERE IDEMPRESA IS NOT NULL AND IDEMPRESA<>1)
    THROW 53303,'Sucursales o pertenencia cambiaron; no reasignar automaticamente.',1;
  UPDATE s SET IDEMPRESA=1 OUTPUT inserted.SUC,deleted.IDEMPRESA,inserted.IDEMPRESA INTO @cambios
    FROM dbo.DAT_SUC s JOIN @whitelist w ON w.SUC=s.SUC WHERE s.IDEMPRESA IS NULL;
  INSERT dbo.EMPRESA_CFG_AUDIT(CORRELACION,IDEMPRESA,SUC,ACCION,ANTES_JSON,DESPUES_JSON,ACTOR)
    SELECT @correlation,1,c.SUC,'VINCULAR_SUCURSAL',
      (SELECT c.ANTES IDEMPRESA FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES),
      (SELECT c.DESPUES IDEMPRESA FOR JSON PATH,WITHOUT_ARRAY_WRAPPER),ORIGINAL_LOGIN() FROM @cambios c;
  IF NOT EXISTS(SELECT 1 FROM dbo.EMPRESA_CFG WITH(UPDLOCK,HOLDLOCK) WHERE IDEMPRESA=1 AND CLAVE='CRED_PERMITIR_PARCIALIDADES')
  BEGIN
    INSERT dbo.EMPRESA_CFG(IDEMPRESA,CLAVE,MODO,VALOR_BIT,MODIFICADO_POR)
      VALUES(1,'CRED_PERMITIR_PARCIALIDADES','EMPRESA',1,ORIGINAL_LOGIN());
    INSERT dbo.EMPRESA_CFG_AUDIT(CORRELACION,IDEMPRESA,CLAVE,ACCION,DESPUES_JSON,ACTOR)
      VALUES(@correlation,1,'CRED_PERMITIR_PARCIALIDADES','CONFIG_INICIAL',N'{"MODO":"EMPRESA","VALOR_BIT":true}',ORIGINAL_LOGIN());
  END;
  IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('dbo.DAT_CTRL_CTAS') AND name='IX_DAT_CTRL_CTAS_CREDITO_SALDO')
    CREATE INDEX IX_DAT_CTRL_CTAS_CREDITO_SALDO ON dbo.DAT_CTRL_CTAS(IDFOL,CLIENT,CTA) INCLUDE(IMPT,CLSD,FCND);
  COMMIT;
  SELECT COUNT(*) SUCURSALES_VINCULADAS FROM dbo.DAT_SUC WHERE IDEMPRESA=1;
  EXEC dbo.sp_creditos_config_get @IDEMPRESA=1;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;
  THROW;
END CATCH;
