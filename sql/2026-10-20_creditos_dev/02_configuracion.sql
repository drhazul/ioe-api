CREATE OR ALTER FUNCTION dbo.fn_creditos_config_efectiva(@SUC nvarchar(10))
RETURNS TABLE AS RETURN
  SELECT s.SUC,s.IDEMPRESA,e.MODO,e.VALOR_BIT VALOR_EMPRESA,s.CRED_PAGO_PARCIAL VALOR_SUCURSAL,
    CONVERT(bit,CASE WHEN e.MODO='EMPRESA' THEN e.VALOR_BIT ELSE COALESCE(s.CRED_PAGO_PARCIAL,e.VALOR_BIT) END) PERMITIR_PARCIAL,
    e.VERSION VERSION_EMPRESA,s.CFG_VERSION VERSION_SUCURSAL
  FROM dbo.DAT_SUC s JOIN dbo.EMPRESA_CFG e ON e.IDEMPRESA=s.IDEMPRESA
  WHERE s.SUC=@SUC AND e.CLAVE='CRED_PERMITIR_PARCIALIDADES';
GO
CREATE OR ALTER PROCEDURE dbo.sp_creditos_config_get @IDEMPRESA int
AS
BEGIN
  SET NOCOUNT ON;
  IF NOT EXISTS(SELECT 1 FROM dbo.EMPRESA WHERE idempresa=@IDEMPRESA) THROW 53400,'Empresa inexistente.',1;
  SELECT e.*,d.ETIQUETA,d.SEGMENTO,d.COLUMNA_SUC FROM dbo.EMPRESA_CFG e
    JOIN dbo.DAT_CFG_DEF d ON d.CLAVE=e.CLAVE WHERE e.IDEMPRESA=@IDEMPRESA;
  SELECT s.[DESC],c.* FROM dbo.DAT_SUC s CROSS APPLY dbo.fn_creditos_config_efectiva(s.SUC) c
    WHERE s.IDEMPRESA=@IDEMPRESA ORDER BY s.SUC;
END;
GO
CREATE OR ALTER PROCEDURE dbo.sp_creditos_config_set
  @IDEMPRESA int,@MODO varchar(12),@PERMITIR bit,@VERSION_ESPERADA binary(8),@ACTOR nvarchar(255)=NULL
AS
BEGIN
  SET NOCOUNT ON; SET XACT_ABORT ON;
  DECLARE @own bit=CASE WHEN @@TRANCOUNT=0 THEN 1 ELSE 0 END,@lock int,@antes nvarchar(max),@despues nvarchar(max),@v binary(8);
  IF @MODO IS NULL OR @MODO NOT IN('EMPRESA','SUCURSAL') OR @PERMITIR IS NULL OR @VERSION_ESPERADA IS NULL
    THROW 53401,'Modo, valor y version esperada son requeridos.',1;
  BEGIN TRY
    IF @own=1 BEGIN TRAN;
    EXEC @lock=sys.sp_getapplock @Resource=N'PS_CREDITOS_CONFIG_V1',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=5000;
    IF @lock<0 THROW 53402,'Configuracion ocupada; reintente.',1;
    SELECT @v=VERSION FROM dbo.EMPRESA_CFG WITH(UPDLOCK,HOLDLOCK)
      WHERE IDEMPRESA=@IDEMPRESA AND CLAVE='CRED_PERMITIR_PARCIALIDADES';
    IF @v IS NULL OR @v<>@VERSION_ESPERADA THROW 53403,'Conflicto de version de configuracion.',1;
    SET @antes=(SELECT MODO,VALOR_BIT FROM dbo.EMPRESA_CFG WHERE IDEMPRESA=@IDEMPRESA
      AND CLAVE='CRED_PERMITIR_PARCIALIDADES' FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
    UPDATE dbo.EMPRESA_CFG SET MODO=@MODO,VALOR_BIT=@PERMITIR,MODIFICADO_UTC=SYSUTCDATETIME(),
      MODIFICADO_POR=COALESCE(NULLIF(@ACTOR,''),ORIGINAL_LOGIN())
      WHERE IDEMPRESA=@IDEMPRESA AND CLAVE='CRED_PERMITIR_PARCIALIDADES' AND VERSION=@VERSION_ESPERADA;
    IF @@ROWCOUNT<>1 THROW 53403,'Conflicto de version de configuracion.',1;
    SET @despues=(SELECT MODO,VALOR_BIT FROM dbo.EMPRESA_CFG WHERE IDEMPRESA=@IDEMPRESA
      AND CLAVE='CRED_PERMITIR_PARCIALIDADES' FOR JSON PATH,WITHOUT_ARRAY_WRAPPER);
    INSERT dbo.EMPRESA_CFG_AUDIT(CORRELACION,IDEMPRESA,CLAVE,ACCION,ANTES_JSON,DESPUES_JSON,ACTOR)
      VALUES(NEWID(),@IDEMPRESA,'CRED_PERMITIR_PARCIALIDADES','CONFIG_EMPRESA',@antes,@despues,
        COALESCE(NULLIF(@ACTOR,''),ORIGINAL_LOGIN()));
    IF @own=1 COMMIT;
    SELECT IDEMPRESA,CLAVE,MODO,VALOR_BIT,VERSION FROM dbo.EMPRESA_CFG
      WHERE IDEMPRESA=@IDEMPRESA AND CLAVE='CRED_PERMITIR_PARCIALIDADES';
  END TRY
  BEGIN CATCH
    IF @own=1 AND @@TRANCOUNT>0 ROLLBACK;
    THROW;
  END CATCH;
END;
GO
CREATE OR ALTER PROCEDURE dbo.sp_creditos_config_sucursal_set
  @IDEMPRESA int,@SUC nvarchar(10),@PERMITIR bit=NULL,@VERSION_ESPERADA binary(8)=NULL,@ACTOR nvarchar(255)=NULL
AS
BEGIN
  SET NOCOUNT ON; SET XACT_ABORT ON;
  DECLARE @own bit=CASE WHEN @@TRANCOUNT=0 THEN 1 ELSE 0 END,@lock int,@v binary(8),@modo varchar(12),@antes nvarchar(max),@despues nvarchar(max);
  IF @VERSION_ESPERADA IS NULL THROW 53404,'Version de sucursal requerida.',1;
  BEGIN TRY
    IF @own=1 BEGIN TRAN;
    EXEC @lock=sys.sp_getapplock @Resource=N'PS_CREDITOS_CONFIG_V1',@LockMode='Exclusive',@LockOwner='Transaction',@LockTimeout=5000;
    IF @lock<0 THROW 53402,'Configuracion ocupada; reintente.',1;
    SELECT @modo=MODO FROM dbo.EMPRESA_CFG WITH(UPDLOCK,HOLDLOCK)
      WHERE IDEMPRESA=@IDEMPRESA AND CLAVE='CRED_PERMITIR_PARCIALIDADES';
    IF ISNULL(@modo,'')<>'SUCURSAL' THROW 53405,'Active modo SUCURSAL antes de editar excepciones.',1;
    SELECT @v=CFG_VERSION FROM dbo.DAT_SUC WITH(UPDLOCK,HOLDLOCK) WHERE SUC=@SUC AND IDEMPRESA=@IDEMPRESA;
    IF @v IS NULL OR @v<>@VERSION_ESPERADA THROW 53406,'Sucursal ajena o version desactualizada.',1;
    SET @antes=(SELECT CRED_PAGO_PARCIAL FROM dbo.DAT_SUC WHERE SUC=@SUC FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES);
    UPDATE dbo.DAT_SUC SET CRED_PAGO_PARCIAL=@PERMITIR WHERE SUC=@SUC AND IDEMPRESA=@IDEMPRESA AND CFG_VERSION=@VERSION_ESPERADA;
    IF @@ROWCOUNT<>1 THROW 53406,'Version de sucursal desactualizada.',1;
    SET @despues=(SELECT CRED_PAGO_PARCIAL FROM dbo.DAT_SUC WHERE SUC=@SUC FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES);
    INSERT dbo.EMPRESA_CFG_AUDIT(CORRELACION,IDEMPRESA,CLAVE,SUC,ACCION,ANTES_JSON,DESPUES_JSON,ACTOR)
      VALUES(NEWID(),@IDEMPRESA,'CRED_PERMITIR_PARCIALIDADES',@SUC,'CONFIG_SUCURSAL',@antes,@despues,
        COALESCE(NULLIF(@ACTOR,''),ORIGINAL_LOGIN()));
    IF @own=1 COMMIT;
    SELECT * FROM dbo.fn_creditos_config_efectiva(@SUC);
  END TRY
  BEGIN CATCH
    IF @own=1 AND @@TRANCOUNT>0 ROLLBACK;
    THROW;
  END CATCH;
END;
