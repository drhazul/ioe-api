/* Estructura de desarrollo, derivada del plan aprobado. Default VALIDAR. No asigna sucursales ni activa reglas.
   Revisar diff de esquema y dependencias en entorno de ensayo antes de aplicar.
   No contiene cambios a sp_ps_pago_finalize: su integracion sigue en el plan.
   Ejecutar completo sin GO. @Aplicar=0 no modifica objetos persistentes.
*/
IF DB_NAME()<>N'IOEDESARROLLO' THROW 53301,'Script exclusivo de IOEDESARROLLO.',1;
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;
DECLARE @Aplicar bit=0,@ServidorEsperado nvarchar(128)=NULL,@BaseEsperada sysname=N'IOEDESARROLLO';
IF @@TRANCOUNT<>0 THROW 52100,'Ejecutar sin transaccion externa.',1;
SELECT N'PV_CTR_FOL_ASVR.FCNPGOCRED datetime2(3) NULL' CAMBIO UNION ALL
SELECT N'DAT_SUC.IDEMPRESA int NULL -> EMPRESA.idempresa, sin asignacion automatica' UNION ALL
SELECT N'DAT_SUC.CRED_PAGO_PARCIAL bit NULL: NULL hereda, 0 total, 1 parcial' UNION ALL
SELECT N'DAT_SUC.CFG_VERSION rowversion: control de concurrencia de configuracion' UNION ALL
SELECT N'DAT_CFG_DEF, EMPRESA_CFG, EMPRESA_CFG_AUDIT: catalogo, valor y auditoria' UNION ALL
SELECT N'PV_CRED_FECHA_AUDIT: ledger reversible de fechas' UNION ALL
SELECT N'PV_CRED_ABONO_REL: vinculo estructurado para nuevos abonos';
IF @Aplicar=1
BEGIN
  IF @ServidorEsperado IS NULL OR @@SERVERNAME<>@ServidorEsperado OR DB_NAME()<>@BaseEsperada
    THROW 52101,'Destino exacto requerido.',1;
  IF OBJECT_ID('dbo.EMPRESA','U') IS NULL OR OBJECT_ID('dbo.DAT_SUC','U') IS NULL
    OR OBJECT_ID('dbo.PV_CTR_FOL_ASVR','U') IS NULL OR OBJECT_ID('dbo.DAT_CTRL_CTAS','U') IS NULL
    THROW 52102,'Faltan tablas base.',1;
  /* Perfil version 1: objetos preexistentes deben revisarse, no asumirse equivalentes. */
  IF OBJECT_ID('dbo.DAT_CFG_DEF','U') IS NOT NULL OR OBJECT_ID('dbo.EMPRESA_CFG','U') IS NOT NULL
    OR OBJECT_ID('dbo.EMPRESA_CFG_AUDIT','U') IS NOT NULL OR OBJECT_ID('dbo.PV_CRED_FECHA_AUDIT','U') IS NOT NULL
    OR OBJECT_ID('dbo.PV_CRED_ABONO_REL','U') IS NOT NULL
    OR COL_LENGTH('dbo.DAT_SUC','IDEMPRESA') IS NOT NULL
    OR COL_LENGTH('dbo.DAT_SUC','CRED_PAGO_PARCIAL') IS NOT NULL
    OR COL_LENGTH('dbo.DAT_SUC','CFG_VERSION') IS NOT NULL
    OR COL_LENGTH('dbo.PV_CTR_FOL_ASVR','FCNPGOCRED') IS NOT NULL
    THROW 52103,'Esquema parcial/existente: comparar version y generar delta; no recrear.',1;
  BEGIN TRY
    BEGIN TRAN;
    ALTER TABLE dbo.PV_CTR_FOL_ASVR ADD FCNPGOCRED datetime2(3) NULL;
    ALTER TABLE dbo.DAT_SUC ADD IDEMPRESA int NULL,CRED_PAGO_PARCIAL bit NULL,CFG_VERSION rowversion;
    EXEC(N'ALTER TABLE dbo.DAT_SUC WITH CHECK ADD CONSTRAINT FK_DAT_SUC_EMPRESA_CFG
      FOREIGN KEY(IDEMPRESA) REFERENCES dbo.EMPRESA(idempresa);
      CREATE INDEX IX_DAT_SUC_IDEMPRESA_CFG ON dbo.DAT_SUC(IDEMPRESA);');
    EXEC(N'CREATE TABLE dbo.DAT_CFG_DEF(
      CLAVE varchar(80) NOT NULL CONSTRAINT PK_DAT_CFG_DEF PRIMARY KEY,
      SEGMENTO nvarchar(80) NOT NULL,
      ETIQUETA nvarchar(200) NOT NULL,
      TIPO varchar(12) NOT NULL CONSTRAINT CK_DAT_CFG_DEF_TIPO CHECK(TIPO=''BIT''),
      COLUMNA_SUC sysname NOT NULL CONSTRAINT UQ_DAT_CFG_DEF_COLUMNA UNIQUE,
      VALOR_INICIAL_BIT bit NOT NULL,
      ACTIVA bit NOT NULL CONSTRAINT DF_DAT_CFG_DEF_ACTIVA DEFAULT(1),
      ORDEN int NOT NULL CONSTRAINT DF_DAT_CFG_DEF_ORDEN DEFAULT(0)
    );
    CREATE TABLE dbo.EMPRESA_CFG(
      IDEMPRESA int NOT NULL,
      CLAVE varchar(80) NOT NULL,
      MODO varchar(12) NOT NULL CONSTRAINT CK_EMPRESA_CFG_MODO CHECK(MODO IN(''EMPRESA'',''SUCURSAL'')),
      VALOR_BIT bit NOT NULL,
      MODIFICADO_POR nvarchar(255) NOT NULL,
      MODIFICADO_UTC datetime2(7) NOT NULL CONSTRAINT DF_EMPRESA_CFG_UTC DEFAULT(SYSUTCDATETIME()),
      VERSION rowversion,
      CONSTRAINT PK_EMPRESA_CFG PRIMARY KEY(IDEMPRESA,CLAVE),
      CONSTRAINT FK_EMPRESA_CFG_EMPRESA FOREIGN KEY(IDEMPRESA) REFERENCES dbo.EMPRESA(idempresa),
      CONSTRAINT FK_EMPRESA_CFG_DEF FOREIGN KEY(CLAVE) REFERENCES dbo.DAT_CFG_DEF(CLAVE)
    );
    CREATE TABLE dbo.EMPRESA_CFG_AUDIT(
      ID bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_EMPRESA_CFG_AUDIT PRIMARY KEY,
      CORRELACION uniqueidentifier NOT NULL,
      IDEMPRESA int NOT NULL,
      CLAVE varchar(80) NULL,
      SUC nvarchar(10) NULL,
      ACCION varchar(40) NOT NULL,
      ANTES_JSON nvarchar(max) NULL,
      DESPUES_JSON nvarchar(max) NOT NULL,
      ACTOR nvarchar(255) NOT NULL,
      FCNR_UTC datetime2(7) NOT NULL CONSTRAINT DF_EMPRESA_CFG_AUDIT_UTC DEFAULT(SYSUTCDATETIME()),
      CONSTRAINT CK_EMPRESA_CFG_AUDIT_JSON CHECK(ISJSON(DESPUES_JSON)=1 AND (ANTES_JSON IS NULL OR ISJSON(ANTES_JSON)=1))
    );
    INSERT dbo.DAT_CFG_DEF(CLAVE,SEGMENTO,ETIQUETA,TIPO,COLUMNA_SUC,VALOR_INICIAL_BIT,ORDEN)
    VALUES(''CRED_PERMITIR_PARCIALIDADES'',N''CREDITOS'',N''Permitir pago en parcialidades en creditos'',
      ''BIT'',''CRED_PAGO_PARCIAL'',1,10);');
    EXEC(N'CREATE TABLE dbo.PV_CRED_FECHA_AUDIT(
      ID bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_PV_CRED_FECHA_AUDIT PRIMARY KEY,
      BATCH_ID uniqueidentifier NOT NULL,
      IDFOL nvarchar(255) NOT NULL,
      CLIENT float NOT NULL,
      CTA nvarchar(255) NOT NULL,
      FECHA_ANTES datetime2(3) NULL,
      FECHA_DESPUES datetime2(3) NULL,
      FECHA_REGISTRO datetime2(3) NULL,
      POLITICA_FECHA varchar(20) NULL,
      IDFOL_PS nvarchar(255) NULL,
      HASH_FUENTE varbinary(32) NULL,
      ACTOR nvarchar(255) NOT NULL CONSTRAINT DF_PV_CRED_FECHA_ACTOR DEFAULT(ORIGINAL_LOGIN()),
      FCNR_UTC datetime2(7) NOT NULL,
      CONSTRAINT UQ_PV_CRED_FECHA_BATCH UNIQUE(BATCH_ID,IDFOL,CLIENT,CTA)
    );
    CREATE TABLE dbo.PV_CRED_ABONO_REL(
      NDOC nvarchar(255) NOT NULL CONSTRAINT PK_PV_CRED_ABONO_REL PRIMARY KEY,
      IDFOL_PS nvarchar(255) NOT NULL,
      IDFOL_CREDITO nvarchar(255) NOT NULL,
      CLIENT float NOT NULL,
      CTA nvarchar(255) NOT NULL,
      IMPORTE decimal(19,4) NOT NULL CONSTRAINT CK_PV_CRED_ABONO_IMPORTE CHECK(IMPORTE>0),
      FECHA_PAGO datetime2(3) NOT NULL,
      ANULADO bit NOT NULL CONSTRAINT DF_PV_CRED_ABONO_ANULADO DEFAULT(0),
      FCNR_UTC datetime2(7) NOT NULL CONSTRAINT DF_PV_CRED_ABONO_UTC DEFAULT(SYSUTCDATETIME()),
      CONSTRAINT FK_PV_CRED_ABONO_MOV FOREIGN KEY(NDOC) REFERENCES dbo.DAT_CTRL_CTAS(NDOC),
      CONSTRAINT FK_PV_CRED_ABONO_CRED FOREIGN KEY(IDFOL_CREDITO) REFERENCES dbo.PV_CTR_FOL_ASVR(IDFOL),
      CONSTRAINT FK_PV_CRED_ABONO_PS FOREIGN KEY(IDFOL_PS) REFERENCES dbo.PV_CTR_FOL_ASVR(IDFOL)
    );
    CREATE INDEX IX_PV_CRED_ABONO_CRED ON dbo.PV_CRED_ABONO_REL(IDFOL_CREDITO,CLIENT,CTA,FECHA_PAGO);');
    /* El sistema queda pendiente de mapeo y configuracion: no INSERT EMPRESA_CFG ni UPDATE DAT_SUC. */
    COMMIT;
  END TRY
  BEGIN CATCH
    IF @@TRANCOUNT>0 ROLLBACK;
    THROW;
  END CATCH;
END;
