/* PROPUESTA 2026-10-20. VALIDAR probado; APLICAR no ejecutado ni autorizado.
   Ejecutar batch completo en una sola sesion. Sin GO. No usar NOLOCK.
   Alcance conservador: CTA CR 101001002; referencias exactas; no deduce aliases.
   FCNPGOCRED pertenece al credito original, nunca al ticket que cobra.
   Fechas son valores SQL sin zona; el cliente no debe interpretar sufijo Z como prueba UTC.
*/
IF DB_NAME()<>N'IOEDESARROLLO' THROW 53301,'Script exclusivo de IOEDESARROLLO.',1;
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 5000;
SET DEADLOCK_PRIORITY LOW;
DECLARE @Aplicar bit = 0;
DECLARE @ServidorEsperado nvarchar(128) = NULL; -- requerido para APLICAR
DECLARE @BaseEsperada sysname = N'IOEDESARROLLO';
DECLARE @HashAprobado varchar(64) = NULL;
DECLARE @ConteoAprobado int = NULL;
DECLARE @FoliosJson nvarchar(max) = NULL; -- ["IDFOL exacto",...], obligatorio APLICAR
DECLARE @IncluirEstadoC bit = 0; -- requiere evidencia y autorizacion aparte
DECLARE @PoliticaFecha varchar(20) = 'PENDIENTE'; -- REGISTRO | UTC_A_MEXICO
DECLARE @Desde datetime2(3) = NULL, @HastaExclusiva datetime2(3) = NULL;
DECLARE @Batch uniqueidentifier = NEWID(), @CorteUtc datetime2(7) = SYSUTCDATETIME();
IF @@TRANCOUNT <> 0 THROW 52000, 'Ejecutar sin transaccion externa.', 1;
IF DB_NAME() <> @BaseEsperada THROW 52001, 'Base distinta a la esperada.', 1;
IF @Aplicar=1 AND (@ServidorEsperado IS NULL OR @@SERVERNAME<>@ServidorEsperado)
  THROW 52002, 'Destino exacto requerido para APLICAR.', 1;
IF @PoliticaFecha NOT IN ('PENDIENTE','REGISTRO','UTC_A_MEXICO')
  THROW 52003, 'Politica de fecha invalida.', 1;
IF @Desde IS NOT NULL AND @HastaExclusiva IS NOT NULL AND @Desde>=@HastaExclusiva
  THROW 52004, 'Rango de fechas invalido.', 1;
IF @Aplicar=1 AND (@PoliticaFecha='PENDIENTE' OR @FoliosJson IS NULL
  OR @HashAprobado IS NULL OR @ConteoAprobado IS NULL)
  THROW 52005, 'Faltan politica temporal, whitelist, conteo o hash revisados.', 1;
IF @FoliosJson IS NOT NULL AND ISJSON(@FoliosJson)<>1 THROW 52006,'Whitelist JSON invalida.',1;
IF @FoliosJson IS NOT NULL AND (LEFT(LTRIM(@FoliosJson),1)<>'['
  OR EXISTS(SELECT 1 FROM OPENJSON(@FoliosJson) WHERE [type]<>1 OR LEN([value])=0 OR LEN([value])>255))
  THROW 52006,'Whitelist debe ser arreglo de folios string no vacios.',1;
IF OBJECT_ID('dbo.PV_CTR_FOL_FORM','U') IS NULL
  THROW 52007,'Adaptar fuente de formas: esta version requiere PV_CTR_FOL_FORM.',1;

BEGIN TRY
  SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;
  BEGIN TRANSACTION;
  CREATE TABLE #CR_Whitelist(IDFOL nvarchar(255) NOT NULL PRIMARY KEY);
  IF @FoliosJson IS NOT NULL
    INSERT #CR_Whitelist SELECT DISTINCT UPPER(LTRIM(RTRIM(CONVERT(nvarchar(255),[value])))) FROM OPENJSON(@FoliosJson);
  IF NOT EXISTS(SELECT 1 FROM dbo.DAT_CAT_CTAS WHERE RELACION='CR' AND CTA='101001002')
    OR EXISTS(SELECT 1 FROM dbo.DAT_CAT_CTAS WHERE RELACION='CR' AND (CTA IS NULL OR CTA<>'101001002'))
    THROW 52008,'Mapeo CR distinto al perfil revisado; detener.',1;
  IF NOT EXISTS(SELECT 1 FROM dbo.DAT_CMOV WHERE RELACION='CR' AND TIPO='ABONO' AND CMOV=601)
    OR NOT EXISTS(SELECT 1 FROM dbo.DAT_CMOV WHERE RELACION='CR' AND TIPO='CARGO' AND CMOV=602)
    OR EXISTS(SELECT 1 FROM dbo.DAT_CMOV WHERE RELACION='CR' AND
      ((TIPO='ABONO' AND CMOV<>601) OR (TIPO='CARGO' AND CMOV<>602)))
    THROW 52008,'Clases CR distintas al perfil revisado; detener.',1;

  SELECT c.NDOC, UPPER(LTRIM(RTRIM(c.IDFOL))) IDFOL,c.CLIENT,c.CTA,c.SUC,c.FCND,
    c.CLSD,c.RTXT,CONVERT(decimal(19,4),c.IMPT) IMPT
  INTO #CR_Mov FROM dbo.DAT_CTRL_CTAS c WHERE c.CTA='101001002';

  SELECT p.IDFOL,p.IDFOLINICIAL,p.CLIEN,p.SUC,p.ESTA,p.FPGO,
    CONVERT(datetime2(3),NULL) FECHA_ACTUAL,
    (SELECT COUNT(*) FROM dbo.PV_CTR_FOL_FORM f
      WHERE f.IDFOL=p.IDFOL AND UPPER(LTRIM(RTRIM(f.FORM)))='CREDITO') FORMAS_CREDITO
  INTO #CR_Origen FROM dbo.PV_CTR_FOL_ASVR p
  WHERE EXISTS(SELECT 1 FROM #CR_Mov m WHERE m.IDFOL=p.IDFOL);
  IF COL_LENGTH('dbo.PV_CTR_FOL_ASVR','FCNPGOCRED') IS NOT NULL
    EXEC sys.sp_executesql N'UPDATE o SET FECHA_ACTUAL=p.FCNPGOCRED
      FROM #CR_Origen o JOIN dbo.PV_CTR_FOL_ASVR p ON p.IDFOL=o.IDFOL;';

  SELECT UPPER(LTRIM(RTRIM(t.IDFOL))) IDFOL_PS,UPPER(LTRIM(RTRIM(t.ORD))) IDFOL_CREDITO,p.CLIEN,p.SUC,p.ESTA,
    SUM(ROUND(CONVERT(decimal(19,4),t.PVTA)*COALESCE(NULLIF(CONVERT(decimal(19,4),t.CTD),0),1),4)) ABONO,
    COUNT(*) LINEAS,
    SUM(CASE WHEN t.PVTA IS NULL OR t.PVTA<=0 OR t.CTD IS NULL OR t.CTD<=0 THEN 1 ELSE 0 END) INVALIDAS
  INTO #CR_PS FROM dbo.PV_TICKET_LOG t
    JOIN dbo.PV_CTR_FOL_ASVR p ON p.IDFOL=t.IDFOL
  WHERE UPPER(LTRIM(RTRIM(t.UPC)))='CR'
  GROUP BY UPPER(LTRIM(RTRIM(t.IDFOL))),UPPER(LTRIM(RTRIM(t.ORD))),p.CLIEN,p.SUC,p.ESTA;

  SELECT UPPER(LTRIM(RTRIM(f.IDFOL))) IDFOL,MIN(f.FCN) FECHA_MIN,MAX(f.FCN) FECHA_MAX,COUNT(*) FORMAS,
    SUM(CASE WHEN f.FCN IS NULL OR f.IMPP IS NULL OR f.IMPC IS NULL THEN 1 ELSE 0 END) INVALIDAS,
    SUM(CONVERT(decimal(19,4),f.IMPP)-CONVERT(decimal(19,4),f.IMPC)) APLICADO
  INTO #CR_Formas FROM dbo.PV_CTR_FOL_FORM f
  WHERE EXISTS(SELECT 1 FROM #CR_PS p WHERE p.IDFOL_PS=f.IDFOL)
  GROUP BY UPPER(LTRIM(RTRIM(f.IDFOL)));
  SELECT UPPER(LTRIM(RTRIM(t.IDFOL))) IDFOL,SUM(ROUND(CONVERT(decimal(19,4),t.PVTA)*
    COALESCE(NULLIF(CONVERT(decimal(19,4),t.CTD),0),1),4)) TOTAL,
    SUM(CASE WHEN t.PVTA IS NULL OR t.CTD IS NULL OR t.CTD<=0 THEN 1 ELSE 0 END) INVALIDAS
  INTO #CR_Totales FROM dbo.PV_TICKET_LOG t
  WHERE EXISTS(SELECT 1 FROM #CR_PS p WHERE p.IDFOL_PS=t.IDFOL)
  GROUP BY UPPER(LTRIM(RTRIM(t.IDFOL)));

  /* Agregar por timestamp evita inventar orden cronologico con NDOC aleatorio. */
  ;WITH e AS(
    SELECT IDFOL,CLIENT,FCND,SUM(IMPT) IMPORTE,
      SUM(CASE WHEN CLSD='601' AND IMPT>0 THEN IMPT ELSE 0 END) ABONO,
      COUNT(DISTINCT RTXT) TEXTOS,MIN(RTXT) RTXT,
      SUM(CASE WHEN FCND IS NOT NULL AND CLIENT IS NOT NULL
        AND ((CLSD='602' AND IMPT<0) OR (CLSD='601' AND IMPT>0)) THEN 0 ELSE 1 END) INVALIDAS,
      SUM(CASE WHEN IMPT<0 THEN 1 ELSE 0 END) CARGOS,
      SUM(CASE WHEN IMPT>0 THEN 1 ELSE 0 END) ABONOS
    FROM #CR_Mov GROUP BY IDFOL,CLIENT,FCND
  ), s AS(
    SELECT *,SUM(IMPORTE) OVER(PARTITION BY IDFOL,CLIENT ORDER BY FCND ROWS UNBOUNDED PRECEDING) SALDO_DESPUES
    FROM e
  ) SELECT *,SALDO_DESPUES-IMPORTE SALDO_ANTES INTO #CR_Eventos FROM s;

  SELECT IDFOL,CLIENT,SUM(IMPORTE) SALDO_FINAL,SUM(INVALIDAS) INVALIDAS,
    SUM(CARGOS) CARGOS,SUM(ABONOS) ABONOS,
    SUM(CASE WHEN SALDO_DESPUES>0 THEN 1 ELSE 0 END) EVENTOS_SOBREPAGO,
    SUM(CASE WHEN CARGOS>0 AND ABONOS>0 THEN 1 ELSE 0 END) EVENTOS_MIXTOS,
    MAX(CASE WHEN SALDO_DESPUES<0 THEN FCND END) ULTIMO_SALDO_NEGATIVO,
    SUM(CASE WHEN SALDO_ANTES<0 AND IMPORTE>0 AND SALDO_DESPUES<0 THEN 1 ELSE 0 END) EVENTOS_PARCIALES
  INTO #CR_Cuentas FROM #CR_Eventos GROUP BY IDFOL,CLIENT;

  SELECT e.IDFOL,e.CLIENT,e.FCND FECHA_REGISTRO,e.IMPORTE,e.RTXT,
    p.IDFOL_PS,p.ESTA ESTADO_PS,p.ABONO ABONO_TICKET,p.LINEAS,
    CASE WHEN @PoliticaFecha='UTC_A_MEXICO' THEN CONVERT(datetime2(3),
      CONVERT(datetime2(3),f.FECHA_MIN) AT TIME ZONE 'UTC' AT TIME ZONE 'Central Standard Time (Mexico)')
      ELSE CONVERT(datetime2(3),f.FECHA_MIN) END FECHA_PROPUESTA,
    COUNT(*) OVER(PARTITION BY e.IDFOL,e.CLIENT,e.FCND) COINCIDENCIAS
  INTO #CR_Enlace FROM #CR_Eventos e
    JOIN #CR_Cuentas c ON c.IDFOL=e.IDFOL AND c.CLIENT=e.CLIENT
    JOIN #CR_PS p ON p.IDFOL_CREDITO=e.IDFOL AND p.CLIEN=e.CLIENT
      AND e.RTXT=CONCAT(N'Abono a cliente ticket ',p.IDFOL_PS)
    JOIN #CR_Formas f ON f.IDFOL=p.IDFOL_PS
    JOIN #CR_Totales tt ON tt.IDFOL=p.IDFOL_PS
  WHERE e.SALDO_ANTES<0 AND e.SALDO_DESPUES=0 AND e.IMPORTE>0
    AND e.FCND>c.ULTIMO_SALDO_NEGATIVO AND e.CARGOS=0 AND e.TEXTOS=1
    AND p.INVALIDAS=0 AND p.ABONO=e.IMPORTE
    AND f.INVALIDAS=0 AND f.FECHA_MIN=f.FECHA_MAX AND f.FECHA_MIN=e.FCND
    AND tt.INVALIDAS=0 AND tt.TOTAL=f.APLICADO;

  SELECT c.*,o.SUC SUC_ORIGEN,o.ESTA ESTADO_ORIGEN,o.FORMAS_CREDITO,o.FECHA_ACTUAL,
    e.IDFOL_PS,e.ESTADO_PS,e.FECHA_REGISTRO,e.FECHA_PROPUESTA,
    CONVERT(varchar(60),CASE
      WHEN o.IDFOL IS NULL THEN 'SIN_CABECERA_O_ALIAS'
      WHEN o.CLIEN IS NULL OR o.CLIEN<>c.CLIENT THEN 'CLIENTE_DISTINTO'
      WHEN (SELECT COUNT(*) FROM #CR_Cuentas x WHERE x.IDFOL=c.IDFOL)<>1 THEN 'MULTIPLES_CLIENTES'
      WHEN o.ESTA IN ('ANULADO','ANULADA','CANCELADO') THEN 'ORIGEN_ANULADO'
      WHEN ISNULL(o.ESTA,'') NOT IN ('MB51PROCES','PAGADO','TRANSMITIR') THEN 'ORIGEN_LEGACY_PENDIENTE'
      WHEN c.INVALIDAS>0 OR c.CARGOS=0 THEN 'MOVIMIENTOS_INVALIDOS'
      WHEN c.SALDO_FINAL<0 THEN 'PENDIENTE'
      WHEN c.SALDO_FINAL>0 OR c.EVENTOS_SOBREPAGO>0 THEN 'SOBREPAGO_REVISAR'
      WHEN c.EVENTOS_MIXTOS>0 THEN 'ORDEN_INTRAFECHA_AMBIGUO'
      WHEN ISNULL(o.FORMAS_CREDITO,0)=0 THEN 'SIN_FORMA_CREDITO_VERIFICABLE'
      WHEN e.IDFOL_PS IS NULL THEN 'SIN_ENLACE_UNIVOCO_FECHA_IMPORTE'
      WHEN e.COINCIDENCIAS<>1 THEN 'ENLACE_AMBIGUO'
      WHEN e.ESTADO_PS='C' AND @IncluirEstadoC=0 THEN 'ESTADO_C_REQUIERE_VALIDACION'
      WHEN ISNULL(e.ESTADO_PS,'') NOT IN ('CERRADO_PS','PAGADO','TRANSMITIR','C') THEN 'PS_NO_CONCRETADO'
      WHEN o.FECHA_ACTUAL IS NOT NULL THEN 'FECHA_EXISTENTE_NO_SOBRESCRIBIR'
      WHEN @Desde IS NOT NULL AND e.FECHA_REGISTRO<@Desde THEN 'FUERA_RANGO'
      WHEN @HastaExclusiva IS NOT NULL AND e.FECHA_REGISTRO>=@HastaExclusiva THEN 'FUERA_RANGO'
      WHEN @FoliosJson IS NOT NULL AND NOT EXISTS(SELECT 1 FROM #CR_Whitelist j WHERE j.IDFOL=c.IDFOL) THEN 'FUERA_WHITELIST'
      ELSE 'APTO_ESTRUCTURAL' END) CLASIFICACION
  INTO #CR_Resultado FROM #CR_Cuentas c
    LEFT JOIN #CR_Origen o ON o.IDFOL=c.IDFOL
    OUTER APPLY(SELECT TOP(1) * FROM #CR_Enlace x
      WHERE x.IDFOL=c.IDFOL AND x.CLIENT=c.CLIENT ORDER BY x.FECHA_REGISTRO DESC,x.IDFOL_PS) e;

  /* El trigger legacy ejecuta homologacion en cualquier UPDATE: preservar todos
     los campos previos salvo FCNPGOCRED o abortar el lote completo. */
  SELECT p.* INTO #CR_PreImagen FROM dbo.PV_CTR_FOL_ASVR p
    JOIN #CR_Resultado r ON r.IDFOL=p.IDFOL WHERE r.CLASIFICACION='APTO_ESTRUCTURAL';

  DECLARE @Evidencia nvarchar(max)=(SELECT
    JSON_QUERY((SELECT * FROM #CR_Mov ORDER BY NDOC FOR JSON PATH,INCLUDE_NULL_VALUES)) movimientos,
    JSON_QUERY((SELECT * FROM #CR_Origen ORDER BY IDFOL FOR JSON PATH,INCLUDE_NULL_VALUES)) origenes,
    JSON_QUERY((SELECT * FROM #CR_PS ORDER BY IDFOL_PS,IDFOL_CREDITO FOR JSON PATH,INCLUDE_NULL_VALUES)) pagos,
    JSON_QUERY((SELECT * FROM #CR_Formas ORDER BY IDFOL FOR JSON PATH,INCLUDE_NULL_VALUES)) formas,
    JSON_QUERY((SELECT * FROM #CR_Totales ORDER BY IDFOL FOR JSON PATH,INCLUDE_NULL_VALUES)) totales,
    JSON_QUERY((SELECT * FROM #CR_Resultado ORDER BY IDFOL,CLIENT FOR JSON PATH,INCLUDE_NULL_VALUES)) resultado,
    JSON_QUERY((SELECT * FROM #CR_PreImagen ORDER BY IDFOL FOR JSON PATH,INCLUDE_NULL_VALUES)) cabecerasCompletas,
    @PoliticaFecha politica,@IncluirEstadoC incluirC,@Desde desde,@HastaExclusiva hasta
    FOR JSON PATH,WITHOUT_ARRAY_WRAPPER,INCLUDE_NULL_VALUES);
  DECLARE @Hash varbinary(32)=HASHBYTES('SHA2_256',@Evidencia);
  DECLARE @Conteo int=(SELECT COUNT(*) FROM #CR_Resultado WHERE CLASIFICACION='APTO_ESTRUCTURAL');
  SELECT @@SERVERNAME SERVIDOR,DB_NAME() BASE,@CorteUtc CORTE_UTC,@Aplicar APLICAR,
    @PoliticaFecha POLITICA_FECHA,@Conteo CANDIDATOS,CONVERT(varchar(64),@Hash,2) HASH;
  SELECT CLASIFICACION,COUNT(*) CUENTAS,SUM(EVENTOS_PARCIALES) EVENTOS_PARCIALES
    FROM #CR_Resultado GROUP BY CLASIFICACION ORDER BY CLASIFICACION;
  SELECT COUNT(*) PS_SIN_CABECERA_ORIGEN FROM #CR_PS p
    WHERE NOT EXISTS(SELECT 1 FROM dbo.PV_CTR_FOL_ASVR o WHERE o.IDFOL=p.IDFOL_CREDITO);
  SELECT IDFOL,CLIENT,SUC_ORIGEN,SALDO_FINAL,EVENTOS_PARCIALES,IDFOL_PS,
    ESTADO_PS,FECHA_REGISTRO,FECHA_PROPUESTA,CLASIFICACION
    FROM #CR_Resultado ORDER BY CLASIFICACION,IDFOL,CLIENT;

  IF @Aplicar=1
  BEGIN
    IF @Conteo=0 OR @Conteo<>@ConteoAprobado OR CONVERT(varchar(64),@Hash,2)<>@HashAprobado
    BEGIN
      DECLARE @errorValidacion nvarchar(2048)=CONCAT(N'Conteo/hash distintos. Esperado ',@ConteoAprobado,N' / ',@HashAprobado,
        N'; actual ',@Conteo,N' / ',CONVERT(varchar(64),@Hash,2));
      THROW 52009,@errorValidacion,1;
    END;
    IF (SELECT COUNT(*) FROM OPENJSON(@FoliosJson))<>@Conteo
      OR EXISTS(SELECT [value] FROM OPENJSON(@FoliosJson) GROUP BY [value] HAVING COUNT(*)>1)
      THROW 52010,'Whitelist debe contener exactamente candidatos sin duplicados.',1;
    IF COL_LENGTH('dbo.PV_CTR_FOL_ASVR','FCNPGOCRED') IS NULL
      OR OBJECT_ID('dbo.PV_CRED_FECHA_AUDIT','U') IS NULL
      THROW 52011,'Falta esquema aprobado y ledger.',1;
    EXEC sys.sp_executesql N'
      INSERT dbo.PV_CRED_FECHA_AUDIT
        (BATCH_ID,IDFOL,CLIENT,CTA,FECHA_ANTES,FECHA_DESPUES,FECHA_REGISTRO,POLITICA_FECHA,IDFOL_PS,HASH_FUENTE,FCNR_UTC)
      SELECT @b,r.IDFOL,r.CLIENT,N''101001002'',p.FCNPGOCRED,r.FECHA_PROPUESTA,r.FECHA_REGISTRO,@politica,r.IDFOL_PS,@h,SYSUTCDATETIME()
      FROM #CR_Resultado r JOIN dbo.PV_CTR_FOL_ASVR p ON p.IDFOL=r.IDFOL
      WHERE r.CLASIFICACION=''APTO_ESTRUCTURAL'' AND p.FCNPGOCRED IS NULL;
      IF @@ROWCOUNT<>@n THROW 52012,''Cambio concurrente antes de ledger.'',1;
      UPDATE p SET FCNPGOCRED=r.FECHA_PROPUESTA
      FROM dbo.PV_CTR_FOL_ASVR p JOIN #CR_Resultado r ON r.IDFOL=p.IDFOL
      WHERE r.CLASIFICACION=''APTO_ESTRUCTURAL'' AND p.FCNPGOCRED IS NULL;
      IF @@ROWCOUNT<>@n THROW 52013,''Conteo UPDATE distinto.'',1;
      IF EXISTS(SELECT 1 FROM #CR_Resultado r JOIN dbo.PV_CTR_FOL_ASVR p ON p.IDFOL=r.IDFOL
        WHERE r.CLASIFICACION=''APTO_ESTRUCTURAL'' AND (p.FCNPGOCRED IS NULL OR p.FCNPGOCRED<>r.FECHA_PROPUESTA))
        THROW 52014,''Postflight de fecha fallo.'',1;',
      N'@b uniqueidentifier,@h varbinary(32),@n int,@politica varchar(20)',@b=@Batch,@h=@Hash,@n=@Conteo,@politica=@PoliticaFecha;
    DECLARE @cols nvarchar(max),@guard nvarchar(max);
    SELECT @cols=STRING_AGG(CONVERT(nvarchar(max),QUOTENAME(name)),N',') WITHIN GROUP(ORDER BY column_id)
      FROM sys.columns WHERE object_id=OBJECT_ID('dbo.PV_CTR_FOL_ASVR') AND name<>'FCNPGOCRED';
    SET @guard=N'IF EXISTS(SELECT '+@cols+N' FROM #CR_PreImagen EXCEPT SELECT '+@cols+
      N' FROM dbo.PV_CTR_FOL_ASVR WHERE IDFOL IN(SELECT IDFOL FROM #CR_PreImagen))
      THROW 52015,''Trigger modifico otros campos; lote revertido.'',1;';
    EXEC sys.sp_executesql @guard;
    SELECT @Batch BATCH_APLICADO,@Conteo FILAS;
  END;
  COMMIT;
  SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
END TRY
BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;
  SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
  THROW;
END CATCH;
